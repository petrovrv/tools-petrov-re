import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const PROVENANCE = {
  reference_provenance: 'recomputed',
  provenance_note: 'generated by bench-src/ref/gen_co2pipeline.py with CoolProp HEOS (Span-Wagner CO2) and an independent 2000-segment midpoint march (Darcy-Weisbach/Colebrook, ground heat exchange), Barlow wall thickness and the documented cost equations; forced pipe size, no boosters'
};
const P = benchPaths({ name: 'co2pipeline', page: 'co2pipeline.html', ref: 'co2pipeline_ref.json' });
const TOLS = {
  t: { kind: 'rel', tol: 1e-9 },
  ID: { kind: 'rel', tol: 1e-9 },
  dp: { kind: 'rel', tol: 0.02 },
  p_out: { kind: 'rel', tol: 0.005 },
  T_out: { kind: 'abs', tol: 0.3 },
  linepack: { kind: 'rel', tol: 0.01 },
  capex: { kind: 'rel', tol: 1e-9 },
  lcot: { kind: 'rel', tol: 0.01 }
};
const KEYS = ['t', 'ID', 'dp', 'p_out', 'T_out', 'linepack', 'capex', 'lcot'];
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);
const cases = [];
for (const cc of REF) {
  let got = {}, err = null;
  try {
    await p.evaluate(inputs => { const a = window.__co2pipeline; Object.assign(a.state, inputs, { level: 'full' }); a.ui.sync(); a.ui.run(); }, cc.inputs);
    await p.waitForTimeout(400);
    got = await p.evaluate(() => {
      const o = Diagram.record.build().outputs || {};
      const n = v => (v && typeof v === 'object' && 'value' in v) ? v.value : v;
      return { t: n(o.t), ID: n(o.ID), dp: n(o.dp), p_out: n(o.p_out), T_out: n(o.T_out), linepack: n(o.linepack), capex: n(o.capex), lcot: n(o.lcot), boosters: n(o.boosters) };
    });
  } catch (e) { err = String(e && e.message || e); }
  const cmp = {}; let worst_rel = 0, pass = !err;
  for (const k of KEYS) {
    const exp = cc.ref ? cc.ref[k] : undefined; if (exp === undefined || exp === null) continue;
    const g = got[k]; const T = TOLS[k]; let rel, ok;
    if (typeof g !== 'number' || !Number.isFinite(g)) { rel = Infinity; ok = false; }
    else {
      const d = Math.abs(g - exp);
      rel = d / Math.max(Math.abs(exp), 1e-300);
      ok = T.kind === 'abs' ? d <= T.tol : rel <= T.tol;
    }
    cmp[k] = { got: g ?? null, exp, rel: Number.isFinite(rel) ? rel : null, ok };
    if (!Number.isFinite(rel) || rel > worst_rel) worst_rel = Number.isFinite(rel) ? rel : Infinity;
    if (!ok) pass = false;
  }
  const boosters = got.boosters;
  const boosterFail = typeof boosters === 'number' && boosters > 0;
  if (boosterFail) pass = false;
  const rec = { id: cc.id, note: cc.note, inputs: cc.inputs, cmp, boosters: boosters ?? null, worst_rel: Number.isFinite(worst_rel) ? worst_rel : null, pass };
  if (err) rec.error = err;
  if (boosterFail) rec.booster_fail = true;
  cases.push(rec);
}
await browser.close();
const total = cases.length; const passed = cases.filter(c => c.pass).length; const failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'co2pipeline', file: 'co2pipeline.html',
  reference: 'CoolProp HEOS (Span-Wagner CO2) with independent 2000-segment midpoint march (Darcy-Weisbach/Colebrook, ground heat exchange), Barlow wall thickness and documented cost equations; forced pipe size, no boosters',
  reference_citations: ['Span R., Wagner W. (1996) J. Phys. Chem. Ref. Data 25:1509', 'Bell I.H. et al., CoolProp', 'ASME B31.4/B31.8 Barlow', 'Colebrook (1939)'],
  tolerance: 't, ID, capex rel 1e-9; dp rel 0.02; p_out rel 0.005; T_out abs 0.3 K (rel reported as abs diff/exp); linepack rel 0.01; lcot rel 0.01; fail if boosters > 0',
  total, passed, failed, page_errors, cases
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`co2pipeline: ${passed}/${total} passed`);
for (const c of cases.filter(c => !c.pass)) {
  const bad = Object.entries(c.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} exp=${v.exp} rel=${v.rel}`).join('; ');
  console.log(`FAIL ${c.id}: ${c.error ? c.error + ' ' : ''}${c.booster_fail ? `boosters=${c.boosters} ` : ''}${bad}`);
}
if (page_errors.length) console.log(`page errors: ${page_errors.length}`);
process.exitCode = 0;
