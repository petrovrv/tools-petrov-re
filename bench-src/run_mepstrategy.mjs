// Benchmark driver for mepstrategy.html (MEP Maintenance Strategy, RCM).
// Reference: bench-src/ref/gen_mepstrategy.py (independent Python, from the published method).
// Run: BENCH_BASE=http://127.0.0.1:8794 node --import file:///C:/Users/Admin/aiwb-site/ops/pw-register.mjs bench-src/run_mepstrategy.mjs
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference decisions and numbers generated by bench-src/ref/gen_mepstrategy.py, an independent standard-library Python implementation of the SAE JA1011/JA1012 / Moubray RCM II decision logic, Moubray FFI, the exact proof-test unavailability (Newton inversion), phase-averaged catch probability (numerical) and Weibull age replacement (Barlow-Proschan, dense-grid minimum), written from the published method and not ported from the tool code.' };
const P = benchPaths({ name: 'mepstrategy', page: 'mepstrategy.html', ref: 'mepstrategy_ref.json' });
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const PRESET_IDS = ['filter_dp', 'standby_never', 'fcu_rtf', 'switchboard_redesign', 'sprinkler_statutory', 'ups_battery', 'chiller_pf'];

const browser = await chromium.launch();
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil: 'load' });
await p.waitForTimeout(900);
const BUILD = await readPageManifestRevision(p);

const results = [];
for (const c of REF.cases) {
  const i = c.inputs, e = c.expect;
  let got = null;
  try {
    got = await p.evaluate(({ i, presetIds }) => {
      const m = window.__mepstrategy, st = m.state, E = m.engine;
      const base = presetIds.indexOf(i.base || i.id) >= 0 ? (i.base || i.id) : null;
      if (base) window.DiagramUI.current.example(base);
      else { st.src = 'lib'; st.preset = ''; st.class_id = i.class_id || ''; st.fm_key = i.fm_key || 'custom'; st.reg_asset = ''; }
      st.ff_min_days = i.ff_min_days || 7;
      st.asset_id = i.id; st.cls = i.cls; st.evident = i.evident; st.safety = i.safety; st.pattern = i.pattern;
      st.pf_days = i.pf_days; st.mtbf_y = i.mtbf_y; st.tech = i.tech || ''; st.pf_fraction = i.pf_fraction == null ? 0.5 : i.pf_fraction;
      st.cost_read = i.cost_read || 0; st.access = i.access !== false;
      st.response_days = E.RESPONSE_DAYS[i.cls]; st.u_tol_pct = E.U_TOL[i.cls] * 100; st.p_detect_pct = 90; st.beta = 3;
      st.corrective_eur = i.corrective_eur; st.planned_eur = i.planned_eur; st.downtime_eur_h = i.downtime_eur_h || 0; st.mttr_h = i.mttr_h || 0;
      st.current_kind = 'none'; st.since_test_y = i.since_test_y == null ? null : i.since_test_y; st.insp_days = i.insp_days; st.phase_pct = 50;
      m.ui.sync(); m.ui.run();
      const l = m.last(), d = l.d;
      const tiles = {};
      document.querySelectorAll('.dgu-tile').forEach(t => { const a = t.querySelector('.dgu-tile-l'), v = t.querySelector('.dgu-tile-v'); if (a && v) tiles[a.textContent.trim()] = v.textContent.trim(); });
      const verdict = (document.querySelector('.dgu-verdict') || {}).textContent || '';
      return { kind: d.kind, compulsory: d.compulsory, interval_days: d.interval_days, ffi_days: d.ff.ffi_days, ffi_exact_days: d.ff.ffi_exact_days,
        p_failed_now: d.ff.p_failed_now, interim_days: d.ff.interim_days, u_interim: d.ff.u_interim, governed: !!d.ff.governed_by_statute, p_catch_user: l.catch_user, u_user: l.u_user,
        cbm_p: d.cbm.p_catch, cbm_total: d.cbm.total_y, t_opt: d.time.T_opt_days, t_total: d.time.total_y, rtf: d.rtf_cost_y, tiles, verdict };
    }, { i, presetIds: PRESET_IDS });
  } catch (err) { errs.push('driver ' + c.id + ': ' + String(err && err.message || err)); }
  const cmp = {}; let pass = !!got;
  function chk(name, g, x, tol, rel) {
    if (x === undefined) return;
    let ok;
    if (x === null || g === null || g === undefined) ok = (x === null || x === undefined) && (g === null || g === undefined);
    else if (typeof x === 'number') ok = rel ? Math.abs(g / x - 1) <= tol : Math.abs(g - x) <= tol;
    else ok = g === x;
    cmp[name] = { got: g === undefined ? null : g, exp: x, ok };
    if (!ok) pass = false;
  }
  if (got) {
    chk('kind', got.kind, e.kind);
    chk('compulsory', got.compulsory, e.compulsory);
    if (e.interval_days != null && e.interval_days < 1) chk('interval_continuous', got.interval_days < 1, true);
    else chk('interval_days', got.interval_days, e.interval_days, 0, false);
    if (e.ff && e.ff.ffi_days != null) { chk('ffi_days', got.ffi_days, e.ff.ffi_days, 1e-9, true); chk('ffi_exact_days', got.ffi_exact_days, e.ff.ffi_exact_days, 1e-6, true); }
    if (e.ff && e.ff.p_failed_now != null) chk('p_failed_now', got.p_failed_now, e.ff.p_failed_now, 1e-9, false);
    if (e.p_catch_user != null) chk('p_catch_user', got.p_catch_user, e.p_catch_user, 1e-3, false);
    if (e.u_user != null) chk('u_user', got.u_user, e.u_user, 1e-9, true);
    if (e.cbm && e.cbm.p_catch != null && got.cbm_p != null) chk('cbm_p_catch', got.cbm_p, e.cbm.p_catch, 1e-3, false);
    if (e.cbm && e.cbm.total_y != null && got.cbm_total != null) chk('cbm_total_y', got.cbm_total, e.cbm.total_y, 2e-3, true);
    if (e.time && e.time.T_opt_days != null && got.t_opt != null) chk('t_opt_days', got.t_opt, e.time.T_opt_days, 2e-2, true);
    if (e.time && e.time.total_y != null && got.t_total != null) chk('time_total_y', got.t_total, e.time.total_y, 1e-3, true);
    chk('rtf_cost_y', got.rtf, e.rtf_cost_y, 1e-9, true);
    if (e.statute_governs) chk('statute_governs', got.governed, true);
    if (e.ff && e.ff.interim_days != null) { chk('interim_days', got.interim_days, e.ff.interim_days, 0, false); chk('u_interim', got.u_interim, e.ff.u_interim, 1e-9, true); }
    /* the page must print the decision it computed */
    const kindWord = { cbm: 'Condition-based task', time: 'Scheduled restoration or replacement', ff: 'Failure-finding test', rtf: 'Run to failure', redesign: 'Redesign' }[got.kind];
    chk('verdict_shows_kind', got.verdict.indexOf(kindWord) >= 0, true);
  }
  results.push({ id: c.id, inputs: i, expect_kind: e.kind, cmp, pass });
}
await browser.close();

const total = results.length, passed = results.filter(r => r.pass).length, failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'mepstrategy', file: 'mepstrategy.html',
  reference: 'bench-src/ref/gen_mepstrategy.py (independent Python: RCM decision logic, FFI, exact proof-test unavailability, numerical catch probability, Weibull age replacement)',
  reference_citations: [
    'SAE JA1011 (2009) Evaluation Criteria for Reliability-Centered Maintenance (RCM) Processes',
    'SAE JA1012 (2011) A Guide to the Reliability-Centered Maintenance (RCM) Standard',
    'Moubray J. (1997) Reliability-centred Maintenance, 2nd ed., Butterworth-Heinemann (FFI = 2 U MTBF)',
    'Barlow R.E., Proschan F. (1965) Mathematical Theory of Reliability (age replacement)',
    'NASA (2008) Reliability Centered Maintenance Guide for Facilities and Collateral Equipment'
  ],
  tolerance: 'decision kind, compulsory flag, practical interval and the interim test interval below the practical minimum exact; interim unavailability rel 1e-9; FFI rel 1e-9, exact FFI rel 1e-6, catch probability abs 1e-3 (reference integrates numerically), unavailability rel 1e-9, CBM annual cost rel 2e-3, optimal replacement age rel 2e-2 (flat optimum), its cost rate rel 1e-3; the verdict must name the decided task',
  total, passed, failed, page_errors: errs, cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`mepstrategy: ${passed}/${total} passed`);
for (const r of results.filter(r => !r.pass)) console.log('FAIL', r.id, JSON.stringify(Object.fromEntries(Object.entries(r.cmp).filter(([, v]) => !v.ok))));
if (errs.length) console.log('page errors:', errs.length, errs.slice(0, 5));
process.exitCode = 0;
