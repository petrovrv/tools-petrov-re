MW_WATER = 18.015
KH = 1297.0
NB_K = 72.0


def dose(p):
    inhib, method = p.get("inhib"), p.get("method")
    if inhib not in MW or method not in ("hammerschmidt", "nielsen"):
        return None
    dT, W, xl = p.get("dT"), p.get("W"), p.get("Xlean")
    if xl is None:
        xl = 1.0 if inhib == "MeOH" else 0.8
    try:
        if not (dT > 0 and W > 0 and 0 < xl <= 1):
            return None
    except TypeError:
        return None
    M = MW[inhib]
    if method == "hammerschmidt":
        X = dT * M / (KH + dT * M)
        out = {"X": X, "M": M, "KH": KH}
    else:
        xw = math.exp(-dT / NB_K)
        X = (1 - xw) * M / ((1 - xw) * M + xw * MW_WATER)
        out = {"X": X, "xw": xw, "M": M}
    if X >= xl:
        return None
    msol = W * X / (xl - X)
    out["msol"] = msol
    out["mpure"] = msol * xl
    return out


