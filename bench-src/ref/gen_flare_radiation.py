#!/usr/bin/env python3
"""Independent reference generator: flare radiation, API Std 521:2020 Annex C
simple point-source method. Stdlib only; does not import the tool under test.
Writes flare_radiation_ref.json next to this script and prints the case count.
Code generated by Claude."""
import json
import math
import os

P = 101325.0      # Pa
RU = 8314.462     # J/(kmol K)
DEF = dict(W=50.0, MW=20.0, LHV=46.0e6, Tj=300.0, d=0.6, H=50.0, uw=8.9,
           F=0.25, tau=1.0, Kdesign=6310.0, R=60.0)


def valid(i):
    if any(i[k] <= 0 for k in ("W", "MW", "LHV", "Tj", "d", "Kdesign")):
        return False
    if not (0 < i["F"] < 1) or not (0 < i["tau"] <= 1):
        return False
    return all(i[k] >= 0 for k in ("H", "uw", "R"))


def calc(i):
    Q = i["W"] * i["LHV"]
    L = 0.00326 * Q ** 0.478
    rho = P * i["MW"] / (RU * i["Tj"])
    uj = i["W"] / (rho * math.pi * i["d"] ** 2 / 4)
    c = math.sqrt(1.4 * RU / i["MW"] * i["Tj"])
    th = math.atan(i["uw"] / uj)
    xc = 0.5 * L * math.sin(th)
    yc = i["H"] + 0.5 * L * math.cos(th)
    D = math.sqrt((i["R"] - xc) ** 2 + yc ** 2)
    K = i["tau"] * i["F"] * Q / (4 * math.pi * D ** 2)
    Dreq = math.sqrt(i["tau"] * i["F"] * Q / (4 * math.pi * i["Kdesign"]))
    Rmin = 0.0 if Dreq <= yc else xc + math.sqrt(Dreq ** 2 - yc ** 2)
    adx = abs(i["R"] - xc)
    Hmin = 0.0 if Dreq <= adx else max(
        0.0, math.sqrt(Dreq ** 2 - adx ** 2) - 0.5 * L * math.cos(th))
    return dict(Q=Q / 1e6, L=L, uj=uj, Mach=uj / c, theta=math.degrees(th),
                D=D, K=K / 1e3, Rmin=Rmin, Hmin=Hmin)


CASES = [
    ("defaults", "all default inputs", {}),
    ("api521_annexc", "API 521 Annex C-like example",
     dict(W=45.36, MW=46.1, LHV=50.0e6, Tj=422.0, d=0.762)),
    ("hydrogen_vent", "hydrogen vent, low F",
     dict(W=2.0, MW=2.016, LHV=120e6, Tj=288.0, d=0.15, F=0.15)),
    ("calm_wind", "no wind, vertical flame", dict(uw=0.0)),
    ("strong_wind", "strong wind tilt", dict(uw=20.0)),
    ("tall_stack", "stack height 100 m", dict(H=100.0)),
    ("low_kdesign", "personnel continuous exposure 1.58 kW/m2",
     dict(Kdesign=1580.0)),
    ("tau_0p8", "atmospheric transmissivity 0.8", dict(tau=0.8)),
    ("r_zero", "receptor at stack base", dict(R=0.0)),
    ("large_flow", "large relief flow", dict(W=200.0)),
    ("small_flow", "small flow, small tip", dict(W=5.0, d=0.2)),
    ("propane", "propane properties", dict(MW=44.1, LHV=46.35e6)),
    ("refuse_w0", "zero mass flow", dict(W=0.0)),
    ("refuse_f", "fraction radiated > 1", dict(F=1.2)),
    ("refuse_tau0", "zero transmissivity", dict(tau=0.0)),
]


def main():
    out = []
    for cid, note, over in CASES:
        inp = dict(DEF, **over)
        ok = valid(inp)
        out.append({"id": cid, "note": note,
                    "expect": "ok" if ok else "refuse",
                    "inp": inp, "ref": calc(inp) if ok else {}})
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "flare_radiation_ref.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
    print(len(out))


if __name__ == "__main__":
    main()
