// Benchmark driver for mepmonitoring.html (Condition Monitoring Advisor).
// node --import file:///C:/Users/Admin/aiwb-site/ops/pw-register.mjs bench-src/run_mepmonitoring.mjs  (BENCH_BASE=http://127.0.0.1:8794)
// Reference: bench-src/ref/gen_mepmonitoring.py (numeric phase average of the detection probability,
// Monte Carlo cross-check, bisection break-even) — independent of mep-monitoring.js.
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference generated by bench-src/ref/gen_mepmonitoring.py from the published P–F method (Moubray RCM II; NASA RCM Guide 2008): detection probability by numerical averaging over the inspection phase (50 000 phase points per route case) with a Monte Carlo cross-check, economics from the stated formulas, break-even by bisection; independent of the tool code.' };
const P = benchPaths({ name: 'mepmonitoring', page: 'mepmonitoring.html', ref: 'mepmonitoring_ref.json' });
const TOL = {
  interval_days: { abs: 1e-9 }, recommended_interval_days: { abs: 1e-9 },
  p_detect_lo: { abs: 2e-4 }, p_detect_mid: { abs: 2e-4 }, p_detect_hi: { abs: 2e-4 },
  net_eur_y_lo: { absOrRel: [0.5, 1e-3] }, net_eur_y_mid: { absOrRel: [0.5, 1e-3] }, net_eur_y_hi: { absOrRel: [0.5, 1e-3] },
  cost_eur_y_mid: { absOrRel: [0.01, 1e-6] },
  breakeven_kind_mid: { exact: true }, breakeven_downtime_eur_h_mid: { absOrRel: [0.5, 2e-3] }
};
const raw = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const cases = raw.cases;
const browser = await chromium.launch({ args: ['--no-proxy-server'] });
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String((e && e.message) || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil: 'domcontentloaded', timeout: 120000 });
await p.waitForFunction(() => window.MEPCM && window.__mepmonitoring, null, { timeout: 120000 });
const BUILD = await readPageManifestRevision(p);
const gots = await p.evaluate(jobs => jobs.map(j => {
  try {
    const r = window.MEPCM.evaluate(j.case, j.option);
    return {
      interval_days: r.interval_days, recommended_interval_days: r.recommended_interval_days,
      p_detect_lo: r.lo.p_detect, p_detect_mid: r.mid.p_detect, p_detect_hi: r.hi.p_detect,
      net_eur_y_lo: r.lo.net_eur_y, net_eur_y_mid: r.mid.net_eur_y, net_eur_y_hi: r.hi.net_eur_y,
      cost_eur_y_mid: r.mid.cost_eur_y,
      breakeven_kind_mid: r.mid.breakeven_kind,
      breakeven_downtime_eur_h_mid: r.mid.breakeven_kind === 'finite' ? r.mid.breakeven_downtime_eur_h : null
    };
  } catch (e) { return { error: String((e && e.message) || e) }; }
}), cases.map(c => ({ case: c.case, option: c.option })));
/* the page's own presets must still be the ones the reference restates */
const presetDrift = await p.evaluate(ref => {
  const out = [];
  for (const c of ref) {
    const pr = window.MEPCM.PRESETS.find(x => x.id === c.preset);
    const o = pr && pr.options.find(x => x.id === c.option.id);
    if (!pr || !o) { out.push(c.id + ': missing in page'); continue; }
    for (const k of Object.keys(c.case)) if (JSON.stringify(pr.case[k]) !== JSON.stringify(c.case[k])) out.push(c.id + ': case.' + k);
    for (const k of Object.keys(c.option)) if (JSON.stringify(o[k]) !== JSON.stringify(c.option[k])) out.push(c.id + ': option.' + k);
  }
  return out;
}, cases.filter(c => c.kind === 'preset'));
await Promise.race([browser.close(), new Promise(r => setTimeout(r, 5000))]);

const results = cases.map((k, i) => {
  const got = gots[i] || { error: 'no result' };
  const ref = k.ref || {};
  const cmp = {};
  let pass = !got.error;
  for (const key of Object.keys(TOL)) {
    const t = TOL[key], g = got[key], r = ref[key === 'breakeven_downtime_eur_h_mid' && ref.breakeven_kind_mid !== 'finite' ? '__none' : key];
    let err = null, ok = false;
    if (t.exact) { ok = g === r; }
    else if (r === undefined || r === null) { ok = g === null || g === undefined; }
    else if (typeof g === 'number' && Number.isFinite(g)) {
      err = Math.abs(g - r);
      ok = t.abs !== undefined ? err <= t.abs : err <= Math.max(t.absOrRel[0], t.absOrRel[1] * Math.abs(r));
    }
    cmp[key] = { got: g ?? null, ref: r ?? null, err, ok };
    if (!ok) pass = false;
  }
  return { id: k.id, kind: k.kind, inputs: { case: k.case, option: k.option }, got, ref, cmp, pass };
});
const total = results.length, passed = results.filter(r => r.pass).length, failed = total - passed;
const presetRes = results.filter(r => r.kind === 'preset'), gridRes = results.filter(r => r.kind === 'grid');
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'mepmonitoring', file: 'mepmonitoring.html',
  reference: 'bench-src/ref/gen_mepmonitoring.py — P–F detection probability by numerical phase averaging (Monte Carlo cross-check in mc_crosscheck), annual expected economics, break-even downtime cost by bisection',
  reference_citations: ['Moubray J. (1997) Reliability-centred Maintenance, 2nd ed., Butterworth-Heinemann, ch. 7 (P–F interval, on-condition task interval)',
                        'NASA (2008) Reliability Centered Maintenance Guide for Facilities and Collateral Equipment, §5 (P–F curve, PT&I techniques)',
                        'US DOE FEMP (2010) Operations & Maintenance Best Practices Guide, Release 3.0, ch. 5–6'],
  tolerance: 'intervals exact (1e-9 d); detection probability within 2e-4 absolute (reference uses a 50 000-point phase grid); net benefit within max(0.5 EUR, 0.1 %); monitoring cost within max(0.01 EUR, 1e-6 rel); break-even kind exact and value within max(0.5 EUR/h, 0.2 %)',
  scope: 'MEPCM.evaluate in the loaded page: 17 preset options (6 presets) + 48 grid cases (P–F 10/40/150 d, usable share 0.5/0.9, interval auto/7/30/91 d, pod 0.6/1.0, 3 units, false alarms); ranking/recommendation and the UI are covered by _mep/cm/test.mjs and _mep/cm/browser.mjs',
  total, passed, failed, preset_total: presetRes.length, preset_passed: presetRes.filter(r => r.pass).length,
  grid_total: gridRes.length, grid_passed: gridRes.filter(r => r.pass).length,
  preset_drift: presetDrift, mc_crosscheck: raw.mc_crosscheck,
  page_errors: errs, cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`mepmonitoring: ${passed}/${total} passed (presets ${presetRes.filter(r => r.pass).length}/${presetRes.length}, grid ${gridRes.filter(r => r.pass).length}/${gridRes.length}); preset drift ${presetDrift.length}`);
for (const r of results.filter(r => !r.pass)) {
  const why = r.got.error ? `error=${r.got.error}` : Object.entries(r.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} ref=${v.ref}`).join('; ');
  console.log(`FAIL ${r.id}: ${why}`);
}
if (presetDrift.length) console.log('preset drift: ' + presetDrift.join(', '));
if (errs.length) console.log(`page errors: ${errs.length}`);
process.exit((failed || presetDrift.length || errs.length) ? 1 : 0);
