import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference values generated by bench-src/ref/gen_co2ship.py with CoolProp HEOS (Span-Wagner CO2) and an independent re-implementation of the documented logistics/cost equations.' };
const P = benchPaths({ name: 'co2ship', page: 'co2ship.html', ref: 'co2ship_ref.json' });
const TOL = 1e-6;
const KEYS = ['kWh_t', 'TLiq_C', 'RT_h', 'fleet', 'perTonne'];
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));

const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);

const cases = [];
for (const cc of REF) {
  let got = {}, err = null;
  try {
    await p.evaluate(inputs => {
      const a = window.__co2ship;
      Object.assign(a.state, CCUS.ship.defaults, inputs, { level: 'full' });
      a.ui.sync();
      a.ui.run();
    }, cc.inputs);
    await p.waitForTimeout(120);
    got = await p.evaluate(() => {
      const o = Diagram.record.build().outputs || {};
      const n = v => (v && typeof v === 'object' && 'value' in v) ? v.value : v;
      const E = n(o.E), TL = n(o.TLiq);
      return {
        kWh_t: typeof E === 'number' ? E / 3600 : null,
        TLiq_C: typeof TL === 'number' ? TL - 273.15 : null,
        RT_h: n(o.RT_h), fleet: n(o.fleet), perTonne: n(o.perTonne)
      };
    });
  } catch (e) { err = String(e && e.message || e); }

  const cmp = {};
  let worst_rel = 0, pass = !err;
  for (const k of KEYS) {
    const exp = cc.ref ? cc.ref[k] : undefined;
    if (exp === undefined || exp === null) continue;
    const g = got[k];
    let rel, ok;
    if (typeof g !== 'number' || !Number.isFinite(g)) { rel = Infinity; ok = false; }
    else if (k === 'fleet') { rel = g === exp ? 0 : Math.abs(g - exp) / Math.max(Math.abs(exp), 1); ok = g === exp; }
    else { rel = Math.abs(g - exp) / Math.max(Math.abs(exp), 1e-300); ok = rel <= TOL; }
    cmp[k] = { got: g ?? null, exp, rel: Number.isFinite(rel) ? rel : null, ok };
    if (!Number.isFinite(rel) || rel > worst_rel) worst_rel = Number.isFinite(rel) ? rel : Infinity;
    if (!ok) pass = false;
  }
  const rec = { id: cc.id, note: cc.note, inputs: cc.inputs, cmp, worst_rel: Number.isFinite(worst_rel) ? worst_rel : null, pass };
  if (err) rec.error = err;
  cases.push(rec);
}
await browser.close();

const total = cases.length;
const passed = cases.filter(c => c.pass).length;
const failed = total - passed;

fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'co2ship', file: 'co2ship.html',
  reference: 'CoolProp HEOS CO2 + independent equations via bench-src/ref/gen_co2ship.py',
  reference_citations: ['Span R., Wagner W. (1996) J. Phys. Chem. Ref. Data 25:1509', 'Bell I.H. et al., CoolProp'],
  tolerance: 'relative 1e-6 on record outputs (full precision); fleet exact',
  total, passed, failed, page_errors, cases
}, { build: BUILD, ...PROVENANCE }), null, 1));

console.log(`co2ship: ${passed}/${total} passed`);
for (const c of cases.filter(c => !c.pass)) {
  const bad = Object.entries(c.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} exp=${v.exp} rel=${v.rel}`).join('; ');
  console.log(`FAIL ${c.id}: ${c.error ? c.error + ' ' : ''}${bad}`);
}
if (page_errors.length) console.log(`page errors: ${page_errors.length}`);
process.exitCode = 0;
