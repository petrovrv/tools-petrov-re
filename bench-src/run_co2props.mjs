import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: "recomputed", provenance_note: "Reference values generated by bench-src/ref/gen_co2props.py with CoolProp (HEOS backend: Span-Wagner CO2 EOS; Laesecke-Muzny viscosity; Huber conductivity), computed independently of the tool code." };
const P = benchPaths({ name:'co2props', page:'co2props.html', ref:'co2props_ref.json' });
const ref = JSON.parse(fs.readFileSync(P.ref,'utf8'));
const TOL = 2e-3;
const DEFAULT_KEYS = { pT:['rho','h','s','cp','w','mu','k'], satT:['psat','rhoL','rhoV','hL','hV','dh'] };

const browser = await chromium.launch();
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil:'load' });
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);

const results = [];
for (const c of ref) {
  let read = { tiles:{}, verdict:'' };
  try {
    await p.evaluate(cc => {
      const st = window.__co2props.state;
      st.level = 'simple';
      st.mode = cc.mode;
      st.T = cc.T_C + 273.15;
      if (cc.mode === 'pT') st.p = cc.p_bar * 1e5;
      window.__co2props.ui.sync();
      window.__co2props.ui.run();
    }, c);
    await p.waitForTimeout(80);
    read = await p.evaluate(() => {
      const tiles = {};
      for (const t of document.querySelectorAll('.dgu-tile')) {
        const l = t.querySelector('.dgu-tile-l'), v = t.querySelector('.dgu-tile-v');
        if (!l || !v) continue;
        const key = l.textContent.split('·')[0].trim();
        tiles[key] = parseFloat(v.textContent.replace(/[\s,]/g,''));
      }
      const vd = document.querySelector('.dgu-verdict');
      return { tiles, verdict: vd ? vd.textContent.trim() : '' };
    });
  } catch (e) {
    errs.push('driver: ' + c.id + ': ' + String(e && e.message || e));
  }

  const cmp = {};
  let worst = 0, pass;
  if (c.expect === 'refuse') {
    const keys = (c.ref && Object.keys(c.ref).length) ? Object.keys(c.ref) : DEFAULT_KEYS[c.mode] || [];
    const numeric = keys.filter(k => Number.isFinite(read.tiles[k]));
    for (const k of keys) cmp[k] = { got: Number.isFinite(read.tiles[k]) ? read.tiles[k] : null };
    pass = numeric.length === 0 && read.verdict.length > 0;
    worst = null;
  } else {
    pass = true;
    for (const [k, e] of Object.entries(c.ref || {})) {
      const g = read.tiles[k];
      if (!Number.isFinite(g)) {
        cmp[k] = { got:null, exp:e, rel:null, ok:false };
        pass = false; worst = Infinity;
        continue;
      }
      const rel = Math.abs(g - e) / Math.max(Math.abs(e), 1e-12);
      const ok = rel <= TOL;
      cmp[k] = { got:g, exp:e, rel, ok };
      if (!ok) pass = false;
      if (rel > worst) worst = rel;
    }
    if (!Object.keys(c.ref || {}).length) pass = false;
  }

  results.push({
    id: c.id, note: c.note,
    inputs: { T_C: c.T_C, p_bar: c.mode === 'pT' ? c.p_bar : null },
    expect: c.expect, verdict: read.verdict, cmp,
    worst_rel: (worst === null || Number.isFinite(worst)) ? worst : null,
    pass
  });
}

await browser.close();

const total = results.length;
const passed = results.filter(r => r.pass).length;
const failed = total - passed;

fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'co2props',
  file: 'co2props.html',
  reference: 'CoolProp HEOS CO2 (Span-Wagner EOS; Laesecke-Muzny viscosity; Huber thermal conductivity) via bench-src/ref/gen_co2props.py',
  reference_citations: [
    'Span R., Wagner W. (1996) J. Phys. Chem. Ref. Data 25:1509',
    'Laesecke A., Muzny C.D. (2017) J. Phys. Chem. Ref. Data 46:013107',
    'Huber M.L. et al. (2016) J. Phys. Chem. Ref. Data 45:013102',
    'Bell I.H. et al., CoolProp 6.x'
  ],
  tolerance: 'relative 2e-3 per property (page displays 5 significant digits); refuse cases: no numeric tiles for expected keys and non-empty verdict',
  total, passed, failed,
  page_errors: errs,
  cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));

console.log(`co2props: ${passed}/${total} passed`);
for (const r of results.filter(r => !r.pass)) {
  const bad = Object.entries(r.cmp).filter(([, v]) => v.ok === false || (r.expect === 'refuse' && v.got !== null))
    .map(([k, v]) => `${k}: got=${v.got} exp=${v.exp ?? '-'} rel=${v.rel ?? '-'}`).join('; ');
  console.log(`FAIL ${r.id} [${r.expect}] ${r.note || ''} :: ${bad || 'verdict=' + JSON.stringify(r.verdict)}`);
}
if (errs.length) console.log(`page errors: ${errs.length}`);
process.exitCode = 0;
