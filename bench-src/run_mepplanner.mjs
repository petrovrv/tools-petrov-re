// Benchmark driver for mepplanner.html (MEP Maintenance Planner).
// node --import file:///C:/Users/Admin/aiwb-site/ops/pw-register.mjs --import file:///C:/Users/Admin/aiwb-site/ops/py3-shim.mjs bench-src/run_mepplanner.mjs  (BENCH_BASE=http://127.0.0.1:8794)
// Reference: bench-src/ref/gen_mepplanner.py — ISO 8601 calendar from Python datetime, the deterministic grid placement,
// weekly loads, visits and budget recomputed from the published rules (generate mode), and an independent check of
// every levelled preset plan the page produces (verify mode: calendar, tolerance, windows, grid spacing, hours,
// visits, travel, capacity conflicts, budget, statutory never moved, levelled never worse, each preset's teaching point).
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { spawnSync } from 'child_process';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths, BENCH_SRC } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference generated by bench-src/ref/gen_mepplanner.py from the planner\'s published rules (ISO 8601 weeks via Python datetime; horizon H = ISO weeks of the plan year (52/53); cyclic grid round(p + k·Iw) mod H with n = round(H/Iw); tolerance floor(10 % · Iw) weeks, statutory 0; season/shutdown/blackout windows; one visit per asset, trade and week; budget formula), independent of mep-planner.js; levelled plans are verified against the same rules by the Python script.' };
const P = benchPaths({ name: 'mepplanner', page: 'mepplanner.html', ref: 'mepplanner_ref.json' });
const ref = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const browser = await chromium.launch({ args: ['--no-proxy-server'] });
const ctx = await browser.newContext();
await ctx.addInitScript(() => { try { localStorage.setItem('diagram_learn_mepplanner', '1'); } catch (e) { /* storage blocked */ } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String((e && e.message) || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil: 'domcontentloaded', timeout: 120000 });
await p.waitForFunction(() => window.MEPPlan && window.__mepplanner && window.__diagramReady, null, { timeout: 120000 });
const BUILD = await readPageManifestRevision(p);

const results = [];
/* 1. calendar + deterministic grid cases against the Python reference */
const gots = await p.evaluate(cases => cases.map(c => {
  try {
    if (c.kind === 'calendar') { const cal = window.MEPPlan.calendar(c.year, c.start_week); return { iso_weeks: cal.map(x => x.iso_week), mondays: cal.map(x => x.monday) }; }
    const pl = window.MEPPlan.schedule(c.tasks, c.opts);
    const w = {}; pl.tasks.forEach(t => { w[t.id] = t.weeks.slice().sort((a, b) => a - b); });
    const h = {}; pl.trades.forEach(t => { h[t] = Math.round(pl.metrics.trades[t].task_hours * 1e6) / 1e6; });
    return { weeks_by_task: w, hours_by_trade: h, visits: pl.metrics.visits, budget_total_eur: pl.budget.total_eur, skipped: pl.skipped.length };
  } catch (e) { return { error: String((e && e.message) || e) }; }
}), ref.cases);
ref.cases.forEach((c, i) => {
  const g = gots[i] || { error: 'no result' }, cmp = {};
  let pass = !g.error;
  if (c.kind === 'calendar') {
    cmp.iso_weeks = { ok: JSON.stringify(g.iso_weeks) === JSON.stringify(c.ref.iso_weeks) };
    cmp.mondays = { ok: JSON.stringify(g.mondays) === JSON.stringify(c.ref.mondays), first: g.mondays && g.mondays[0], exp_first: c.ref.mondays[0] };
  } else {
    cmp.weeks_by_task = { ok: JSON.stringify(g.weeks_by_task) === JSON.stringify(c.ref.weeks_by_task), got: g.weeks_by_task, exp: c.ref.weeks_by_task };
    cmp.hours_by_trade = { ok: Object.keys(c.ref.hours_by_trade).every(k => g.hours_by_trade && Math.abs(g.hours_by_trade[k] - c.ref.hours_by_trade[k]) < 1e-6), got: g.hours_by_trade, exp: c.ref.hours_by_trade };
    cmp.visits = { ok: g.visits === c.ref.visits, got: g.visits, exp: c.ref.visits };
    cmp.budget_total_eur = { ok: g.budget_total_eur != null && Math.abs(g.budget_total_eur - c.ref.budget_total_eur) <= 0.02, got: g.budget_total_eur, exp: c.ref.budget_total_eur };
    cmp.skipped = { ok: g.skipped === 0, got: g.skipped };
  }
  for (const v of Object.values(cmp)) if (!v.ok) pass = false;
  results.push({ id: c.id, kind: c.kind, note: c.note || '', cmp, error: g.error || undefined, pass });
});

/* 2. the page's levelled preset plans, verified by the Python reference */
const dump = await p.evaluate(() => {
  const out = [];
  const add = (id, aha, pr, extra) => { const o = Object.assign({}, pr.opts, extra || {}); const c = window.MEPPlan.compare(pr.tasks, o); out.push({ id, aha, opts: c.levelled.opts, levelled: c.levelled, naive: c.naive }); };
  for (const id of window.MEPPlan.PRESET_IDS) add(id, id, window.MEPPlan.preset(id));
  add('chiller_winter_rebaselined', 'chiller_winter_rebaselined', window.MEPPlan.preset('chiller_winter'), { rebaseline: true });
  add('quarterly_peak_by_location', 'none', window.MEPPlan.preset('quarterly_peak'), { group_by: 'none' });
  add('grouping_start_w14', 'none', window.MEPPlan.preset('grouping'), { start_week: 14 });
  add('statutory_locked_2027', 'none', window.MEPPlan.preset('statutory_locked'), { year: 2027 });
  add('statutory_locked_2026_w27', 'none', window.MEPPlan.preset('statutory_locked'), { start_week: 27 });
  return out;
});
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bench-mepplanner-'));
const dumpFile = path.join(tmpDir, 'plans.json');
fs.writeFileSync(dumpFile, JSON.stringify({ cases: dump }));
const py = spawnSync('python3', [path.join(BENCH_SRC, 'ref', 'gen_mepplanner.py'), '--verify', dumpFile], { encoding: 'utf8', maxBuffer: 64 << 20 });
let verified = [];
try { verified = JSON.parse(py.stdout); } catch (e) { errs.push('python verify: ' + (py.stderr || py.error || e).toString().slice(0, 400)); }
for (const v of verified) results.push({ id: 'plan_' + v.id, kind: 'levelled_plan', cmp: { invariants: { ok: v.pass, fails: v.fails } }, summary: v, pass: v.pass });

/* 3. the page shows what the engine computes (tile = engine value) */
await p.evaluate(() => window.DiagramUI.current.example('quarterly_peak'));
await p.waitForTimeout(400);
const ui = await p.evaluate(() => {
  const L = window.__mepplanner.last, tiles = {};
  for (const t of document.querySelectorAll('.dgu-tile')) { const l = t.querySelector('.dgu-tile-l'), v = t.querySelector('.dgu-tile-v'); if (l && v) tiles[l.textContent.replace(/\?/g, '').trim()] = v.textContent.trim(); }
  return { tiles, peakL: L.levelled.metrics.peak_total, peakN: L.naive.metrics.peak_total };
});
const tileNum = s => s == null ? null : parseFloat(String(s).replace(/[\s\u00a0\u202f,]/g, ''));
const tL = tileNum(Object.entries(ui.tiles).find(([k]) => /levelled/i.test(k))?.[1]), tN = tileNum(Object.entries(ui.tiles).find(([k]) => /as set up/i.test(k))?.[1]);
results.push({ id: 'ui_tiles_quarterly_peak', kind: 'ui', cmp: { peak_levelled: { ok: Math.abs(tL - ui.peakL) < 0.051, got: tL, exp: ui.peakL }, peak_naive: { ok: Math.abs(tN - ui.peakN) < 0.051, got: tN, exp: ui.peakN } },
  pass: Math.abs(tL - ui.peakL) < 0.051 && Math.abs(tN - ui.peakN) < 0.051 });
await Promise.race([browser.close(), new Promise(r => setTimeout(r, 5000))]);
fs.rmSync(tmpDir, { recursive: true, force: true });

const total = results.length, passed = results.filter(r => r.pass).length, failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'mepplanner',
  file: 'mepplanner.html',
  reference: 'bench-src/ref/gen_mepplanner.py (Python datetime ISO 8601 calendar; independent re-implementation of the published grid/tolerance/window/visit/budget rules; invariant verification of the page\'s levelled plans)',
  reference_citations: ['ISO 8601-1:2019 week dates', 'EN 13306:2017 Maintenance terminology (scheduled preventive maintenance)', 'US DOE FEMP O&M Best Practices Guide R3 (2010), ch. 9', 'Regulation (EU) 2024/573; Directive (EU) 2024/1275 (statutory intervals as carried by mep-core.js)'],
  tolerance: 'calendar and placement exact; hours 1e-6 h; budget 0.02 EUR; weekly loads 0.011 h (2-decimal rounding in the page); levelled plans: all invariants must hold',
  total, passed, failed,
  page_errors: errs,
  cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`mepplanner: ${passed}/${total} passed`);
for (const r of results.filter(x => !x.pass)) console.log('FAIL ' + r.id + ' :: ' + JSON.stringify(Object.fromEntries(Object.entries(r.cmp).filter(([, v]) => !v.ok))).slice(0, 600));
if (errs.length) console.log('page errors: ' + errs.join(' | '));
process.exitCode = 0;
