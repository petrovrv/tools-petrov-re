import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference generated by bench-src/ref/gen_co2compressor.py with CoolProp HEOS (Span-Wagner CO2), polytropic path N=400, independent of the tool code.' };
const P = benchPaths({ name:'co2compressor', page:'co2compressor.html', ref:'co2compressor_ref.json' });
const TOL = { T2_C: { abs: 0.5 }, w_kJkg: { rel: 5e-3 }, wis_kJkg: { rel: 5e-3 } };
const TOL_SOLVE = {
  nStages: { abs: 0 },
  P_el_MW: { rel: 5e-3 },
  kWh_t: { rel: 5e-3 },
  comp_kWh_t: { rel: 5e-3 },
  pump_kWh_t: { abs: 0.05 },
  liq_kWh_t: { rel: 5e-3 },
  Tout_C: { abs: 0.5 },
  pOut_bar: { rel: 1e-6 }
};
const raw = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const cases = Array.isArray(raw) ? raw : raw.cases;
const isSolve = k => k && k.kind === 'solve';
const browser = await chromium.launch();
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String((e && e.message) || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil: 'load' });
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);
const inputs = cases.map(k => isSolve(k)
  ? k.inputs
  : { p1_bar: k.p1_bar, p2_bar: k.p2_bar, T1_C: k.T1_C, eta_p: k.eta_p });
const jobs = cases.map((k, i) => ({ kind: isSolve(k) ? 'solve' : 'stage', inputs: inputs[i] }));
const gots = await p.evaluate(jobs => {
  const bk = (r, key) => {
    const b = r && r.breakdown;
    if (!b) return undefined;
    if (Array.isArray(b)) {
      const e = b.find(x => x && (x.key === key || x.id === key));
      return e ? (e.value !== undefined ? e.value : e.v) : undefined;
    }
    const v = b[key];
    return (v && typeof v === 'object') ? v.value : v;
  };
  return jobs.map(j => {
    try {
      const c = window.CCUS.core, m = window.CCUS.compress;
      if (j.kind === 'solve') {
        const r = m.solve(j.inputs);
        if (!r || r.ok === false) return { error: String((r && (r.error || r.msg || r.message)) || 'solve returned ok=false') };
        return {
          nStages: r.nStages,
          P_el_MW: r.P_el / 1e6,
          kWh_t: r.kWh_t,
          comp_kWh_t: bk(r, 'e_comp'),
          pump_kWh_t: bk(r, 'e_pump'),
          liq_kWh_t: bk(r, 'e_liq'),
          Tout_C: r.Tout - 273.15,
          pOut_bar: r.pOut / 1e5
        };
      }
      const k = j.inputs;
      const a = { props: (p, T) => c.props(p, T), ph: (p, h) => c.flashPH(p, h), ps: (p, s) => c.flashPS(p, s), satP: p => c.satP(p) };
      const r = m._internal.polyStep(a, k.p1_bar * 1e5, k.T1_C + 273.15, k.p2_bar * 1e5, k.eta_p, (m.defaults && m.defaults.N) || 50);
      return { T2_C: r.T - 273.15, w_kJkg: r.w / 1000, wis_kJkg: r.wIsen / 1000 };
    } catch (e) { return { error: String((e && e.message) || e) }; }
  });
}, jobs).catch(e => jobs.map(() => ({ error: String((e && e.message) || e) })));
await browser.close();
const results = cases.map((k, i) => {
  const kind = isSolve(k) ? 'solve' : 'stage';
  const tol = kind === 'solve' ? TOL_SOLVE : TOL;
  const got = gots[i] || { error: 'no result' };
  const ref = k.ref || {};
  const cmp = {};
  let pass = !got.error;
  for (const key of Object.keys(tol)) {
    const g = got[key], r = ref[key];
    let err = null, ok = false;
    if (typeof g === 'number' && Number.isFinite(g) && typeof r === 'number') {
      err = tol[key].abs !== undefined ? Math.abs(g - r) : Math.abs(g - r) / Math.max(Math.abs(r), 1e-12);
      ok = err <= (tol[key].abs !== undefined ? tol[key].abs : tol[key].rel);
    }
    cmp[key] = { got: g ?? null, ref: r ?? null, err, ok };
    if (!ok) pass = false;
  }
  const out = { id: k.id, kind, note: k.note, inputs: inputs[i], got, ref, cmp, pass };
  if (kind === 'solve') out.preset = k.preset;
  return out;
});
const total = results.length, passed = results.filter(r => r.pass).length, failed = total - passed;
const stageRes = results.filter(r => r.kind === 'stage'), solveRes = results.filter(r => r.kind === 'solve');
const stage_total = stageRes.length, stage_passed = stageRes.filter(r => r.pass).length;
const solve_total = solveRes.length, solve_passed = solveRes.filter(r => r.pass).length;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'co2compressor', file: 'co2compressor.html',
  reference: 'CoolProp HEOS CO2 polytropic stage path (N=400) and full-train solve for the presets via bench-src/ref/gen_co2compressor.py',
  reference_citations: ['Span R., Wagner W. (1996) J. Phys. Chem. Ref. Data 25:1509', 'Bell I.H. et al. (2014) CoolProp, Ind. Eng. Chem. Res. 53:2498'],
  tolerance: 'stage level: outlet T within 0.5 K, polytropic and isentropic specific work within 0.5 % relative (tool integrates with N sub-steps); full-train solve(): stage count exact, electric power, total, compression and liquefaction kWh/t within 0.5 % relative, pump kWh/t within 0.05 absolute, outlet T within 0.5 K, outlet pressure within 1e-6 relative',
  scope: 'stage-level real-gas compression and full-train solve() for the 7 presets (kWh/t, electric power, outlet T, stage count); costs and water not graded',
  total, passed, failed,
  stage_total, stage_passed, solve_total, solve_passed,
  page_errors: errs, cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`co2compressor: ${passed}/${total} passed (stage ${stage_passed}/${stage_total}, solve ${solve_passed}/${solve_total})`);
for (const r of results.filter(r => !r.pass)) {
  const why = r.got.error ? `error=${r.got.error}` : Object.entries(r.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} ref=${v.ref} err=${v.err}`).join('; ');
  console.log(`FAIL ${r.id} [${r.kind}${r.preset ? ':' + r.preset : ''}] (${r.note}): ${why}`);
}
if (errs.length) console.log(`page errors: ${errs.length}`);
process.exitCode = 0;
