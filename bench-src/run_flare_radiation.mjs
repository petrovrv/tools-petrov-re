import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const P = benchPaths({ name: 'flare_radiation', page: 'flare_radiation.html', ref: 'flare_radiation_ref.json' });
const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'generated by bench-src/ref/gen_flare_radiation.py, an independent stdlib-Python implementation of the API Std 521:2020 Annex C point-source equations' };
const KEYS = ['Q', 'L', 'uj', 'Mach', 'theta', 'D', 'K', 'Rmin', 'Hmin'];
const CONV = { Q: v => v / 1e6, theta: v => v * 180 / Math.PI, K: v => v / 1e3 };
const unwrap = v => (v !== null && typeof v === 'object' && 'value' in v) ? v.value : v;
const isNum = v => typeof v === 'number' && Number.isFinite(v);
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String((e && e.message) || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);
const cases = [];
for (const c of REF) {
  const inp = c.inp;
  const rec = { id: c.id, note: c.note, expect: c.expect, inputs: inp, cmp: {}, worst_rel: 0, pass: false };
  let o = {};
  try {
    await p.evaluate(i => {
      const a = window.__flare_radiation;
      Object.assign(a.state, { W: i.W, MW: i.MW, LHV_MJ: i.LHV / 1e6, Tj: i.Tj, d: i.d, H: i.H, uw: i.uw, F: i.F, tau: i.tau, Kd_kW: i.Kdesign / 1e3, R: i.R, level: 'full' });
      a.ui.sync(); a.ui.run();
    }, inp);
    await p.waitForTimeout(300);
    o = (await p.evaluate(() => Diagram.record.build().outputs || {})) || {};
  } catch (e) { rec.error = String((e && e.message) || e); }
  const got = {};
  for (const k of KEYS) { let v = unwrap(o[k]); if (isNum(v) && CONV[k]) v = CONV[k](v); got[k] = v === undefined ? null : v; }
  if (c.expect === 'refuse') {
    for (const k of KEYS) rec.cmp[k] = { got: got[k], exp: null, rel: null, ok: !isNum(got[k]) };
    rec.worst_rel = null;
    rec.pass = KEYS.every(k => rec.cmp[k].ok);
  } else {
    let worst = 0;
    for (const k of KEYS) {
      const exp = c.ref[k], g = got[k];
      let rel = Infinity, ok = false;
      if (isNum(g) && isNum(exp)) {
        const diff = Math.abs(g - exp);
        if (exp === 0) { rel = diff; ok = diff <= 1e-9; } else { rel = diff / Math.abs(exp); ok = rel <= 1e-6; }
      }
      rec.cmp[k] = { got: g, exp, rel: Number.isFinite(rel) ? rel : null, ok };
      worst = Math.max(worst, rel);
    }
    rec.worst_rel = Number.isFinite(worst) ? worst : null;
    rec.pass = !rec.error && KEYS.every(k => rec.cmp[k].ok);
  }
  cases.push(rec);
}
await browser.close();
const total = cases.length;
const passed = cases.filter(c => c.pass).length;
const failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'flare_radiation', file: 'flare_radiation.html',
  reference: 'independent stdlib-Python API Std 521:2020 Annex C point-source implementation (bench-src/ref/gen_flare_radiation.py)',
  reference_citations: ['API Std 521, 7th ed. (2020), Annex C', 'Brzustowski T.A., Sommer E.C. (1973) Proc. API Div. Refining 53:865'],
  tolerance: 'relative 1e-6 per output (absolute 1e-9 when the reference is 0); refused inputs pass only if no numeric outputs',
  total, passed, failed, page_errors, cases
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`flare_radiation: ${passed}/${total} passed`);
for (const c of cases.filter(x => !x.pass)) {
  const bad = KEYS.filter(k => c.cmp[k] && !c.cmp[k].ok).map(k => `${k} got=${c.cmp[k].got} exp=${c.cmp[k].exp}`).join('; ');
  console.log(`FAIL ${c.id} [${c.expect}]: ${bad}${c.error ? ` error=${c.error}` : ''}`);
}
if (page_errors.length) console.log(`page errors: ${page_errors.length}`);
process.exitCode = 0;
