// Benchmark driver for mepspares.html (Critical Spares & Recovery).
// node --import file:///C:/Users/Admin/aiwb-site/ops/pw-register.mjs bench-src/run_mepspares.mjs  (BENCH_BASE=http://127.0.0.1:8794)
// Reference: bench-src/ref/gen_mepspares.py (Poisson terms from lgamma, EBO by its tail-sum definition, redundancy outage by
// Simpson integration, season overlap by numerical phase integration, Monte Carlo of the base-stock system) — independent of mep-spares.js.
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';

const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference generated by bench-src/ref/gen_mepspares.py from the published base-stock method (Palm 1938; Sherbrooke 2004; Little 1961): Poisson probabilities from lgamma, expected backorders by the tail sum of the definition, redundancy outage by Simpson integration of 1 − e^(−rt), season overlap and touch probability by numerical integration over the start phase, Monte Carlo cross-check of fill rate and mean wait; independent of the tool code.' };
const P = benchPaths({ name: 'mepspares', page: 'mepspares.html', ref: 'mepspares_ref.json' });
const OPTS = ['none', 'stock', 'dedicated', 'pool', 'agreement', 'rental'];
const EXACT = ['best', 'best_lo', 'best_hi', 'k_optimum', 'k_service', 'k_stock'];
const NUM = { total_lo: [0.5, 2e-4], total_mid: [0.5, 2e-4], total_hi: [0.5, 2e-4], holding: [1e-6, 1e-9], downtime_h_y: [1e-4, 2e-4],
              recovery_h: [1e-6, 1e-9], fill: [1e-9, 1e-9] };
const raw = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const cases = raw.cases;
const browser = await chromium.launch({ args: ['--no-proxy-server'] });
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String((e && e.message) || e)));
await p.goto(P.pageUrl + '?lang=en', { waitUntil: 'domcontentloaded', timeout: 120000 });
await p.waitForFunction(() => window.MEPSpares && window.__mepspares, null, { timeout: 120000 });
const BUILD = await readPageManifestRevision(p);
const gots = await p.evaluate(jobs => jobs.map(c => {
  try {
    const r = window.MEPSpares.evaluate(c);
    const o = {};
    r.rows.forEach(x => { o[x.id] = { feasible: x.feasible, total_lo: x.lo.total_eur_y, total_mid: x.total_eur_y, total_hi: x.hi.total_eur_y,
                                      holding: x.holding_eur_y, downtime_h_y: x.downtime_h_y, recovery_h: x.recovery_h, fill: x.fill }; });
    return { best: r.best, best_lo: r.best_lo, best_hi: r.best_hi, k_optimum: r.k.optimum, k_service: r.k.service, k_stock: r.k.stock, options: o };
  } catch (e) { return { error: String((e && e.message) || e) }; }
}), cases.map(c => c.case));
/* the page's own presets must still be the ones the reference restates */
const presetDrift = await p.evaluate(ref => {
  const out = [];
  const norm = c => window.MEPSpares.normalise(c);
  for (const c of ref) {
    const pr = window.MEPSpares.PRESETS.find(x => x.id === c.preset);
    if (!pr) { out.push(c.id + ': missing in page'); continue; }
    const a = norm(pr.case), b = norm(c.case);
    ['units', 'rate_y', 'part_cost_eur', 'lead_time_days', 'fit_h', 'obsolete', 'downtime_cost_eur_h', 'tolerable_downtime_h', 'season_share', 'redundancy', 'holding_rate', 'options']
      .forEach(k => { if (JSON.stringify(a[k]) !== JSON.stringify(b[k])) out.push(c.id + ': ' + k); });
  }
  return out;
}, cases.filter(c => c.kind === 'preset'));
await Promise.race([browser.close(), new Promise(r => setTimeout(r, 5000))]);

const results = cases.map((k, i) => {
  const got = gots[i] || { error: 'no result' };
  const ref = k.ref;
  const cmp = {};
  let pass = !got.error;
  if (pass) {
    for (const key of EXACT) { const ok = got[key] === (ref[key] === undefined ? null : ref[key]); cmp[key] = { got: got[key], ref: ref[key], ok }; if (!ok) pass = false; }
    for (const o of OPTS) {
      const g = got.options[o], r = ref.options[o];
      const okF = g.feasible === r.feasible; cmp[o + '.feasible'] = { got: g.feasible, ref: r.feasible, ok: okF }; if (!okF) pass = false;
      for (const [key, [abs, rel]] of Object.entries(NUM)) {
        const err = Math.abs(g[key] - r[key]);
        const ok = Number.isFinite(g[key]) && err <= Math.max(abs, rel * Math.abs(r[key]));
        cmp[o + '.' + key] = { got: g[key], ref: r[key], err, ok };
        if (!ok) pass = false;
      }
    }
  }
  return { id: k.id, kind: k.kind, inputs: k.case, got, ref, cmp, pass };
});
const total = results.length, passed = results.filter(r => r.pass).length, failed = total - passed;
const presetRes = results.filter(r => r.kind === 'preset'), gridRes = results.filter(r => r.kind === 'grid');
const mcOk = raw.mc_crosscheck.every(m => Math.abs(m.fill_mc - m.fill_poisson) < 0.005 && Math.abs(m.wait_mc_y / m.wait_little_y - 1) < 0.03);
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'mepspares', file: 'mepspares.html',
  reference: 'bench-src/ref/gen_mepspares.py — base-stock (S−1, S) model with Poisson demand (lgamma terms, EBO tail sums), Little’s-law mean wait, redundancy outage by Simpson integration, season overlap by numerical phase integration; Monte Carlo cross-check in mc_crosscheck',
  reference_citations: ['Sherbrooke C. C. (2004) Optimal Inventory Modeling of Systems: Multi-Echelon Techniques, 2nd ed., Kluwer, ch. 2 (base-stock model, Palm’s theorem, fill rate, expected backorders)',
                        'Palm C. (1938) Analysis of the Erlang traffic formulae for busy-signal arrangements, Ericsson Technics 4',
                        'Little J. D. C. (1961) A proof for the queuing formula L = λW, Operations Research 9(3)',
                        'Moubray J. (1997) Reliability-centred Maintenance, 2nd ed. (hidden/redundant functions, exposure while the protective device is failed)'],
  tolerance: 'option, stock levels and feasibility exact; totals within max(0.5 EUR, 0.02 %) (reference integrates the season numerically on a 20 000-point phase grid); downtime hours within max(1e-4 h, 0.02 %); recovery time 1e-6 h; holding 1e-6 EUR; fill rate 1e-9',
  scope: 'MEPSpares.evaluate in the loaded page: 6 presets + 4 stress cases (optimum up to tens of spares) + 64 grid cases (units 1/5, rate 0.05/0.5 per unit-year with ×0.5/×2 range, lead 14/120 d, downtime 100/5 000 EUR/h, redundancy credited or not, season share 1/0.5; all six options enabled); UI, register screening and the hand-over link are covered by _mep/spares/test.mjs and _mep/spares/browser.mjs',
  total, passed, failed, preset_total: presetRes.length, preset_passed: presetRes.filter(r => r.pass).length,
  grid_total: gridRes.length, grid_passed: gridRes.filter(r => r.pass).length,
  preset_drift: presetDrift, mc_crosscheck: raw.mc_crosscheck, mc_ok: mcOk,
  page_errors: errs, cases: results
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`mepspares: ${passed}/${total} passed (presets ${presetRes.filter(r => r.pass).length}/${presetRes.length}, grid ${gridRes.filter(r => r.pass).length}/${gridRes.length}); preset drift ${presetDrift.length}; MC ${mcOk ? 'ok' : 'FAIL'}`);
for (const r of results.filter(r => !r.pass).slice(0, 15)) {
  const why = r.got.error ? `error=${r.got.error}` : Object.entries(r.cmp).filter(([, v]) => !v.ok).slice(0, 4).map(([k, v]) => `${k} got=${v.got} ref=${v.ref}`).join('; ');
  console.log(`FAIL ${r.id}: ${why}`);
}
if (presetDrift.length) console.log('preset drift: ' + presetDrift.join(', '));
if (errs.length) console.log(`page errors: ${errs.length}`);
process.exit((failed || presetDrift.length || errs.length || !mcOk) ? 1 : 0);
