import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const P = benchPaths({ name: 'dent_strain', page: 'dent_strain.html', ref: 'dent_strain_ref.json' });
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const TOL = 2e-3;
const MAP = { eps1: ['eps1', 1], eps2: ['eps2', 1], eps3: ['eps3', 1], eps_i: ['eps_i', 1], eps_o: ['eps_o', 1], eps_max: ['eps_max', 1], d_D: ['d_D', 1], verdict: ['verdict', null] };
const val = x => (x && typeof x === 'object' && 'value' in x) ? x.value : x;
const relErr = (got, exp) => Math.abs(got - exp) / Math.max(Math.abs(exp), 1e-12);
const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);
const cases = [];
for (const c of REF.cases) {
  const rec = { id: c.id, note: c.note ?? null, inputs: c.inputs, cmp: {}, worst_rel: 0, pass: false };
  try {
    await p.evaluate(inputs => {
      const a = window.__dent_strain;
      Object.assign(a.state, inputs, { level: 'full' });
      a.ui.sync(); a.ui.run();
    }, c.inputs);
    await p.waitForTimeout(300);
    const o = await p.evaluate(() => {
      const D = typeof Diagram !== 'undefined' ? Diagram : window.Diagram;
      return D.record.build().outputs;
    });
    let ok = true;
    for (const [k, exp] of Object.entries(c.ref || {})) {
      if (exp === null || exp === undefined || !MAP[k]) continue;
      const [src, scale] = MAP[k];
      const raw = val(o?.[src]);
      if (scale === null) {
        const got = raw === undefined ? null : String(raw);
        const good = got === String(exp);
        rec.cmp[k] = { got, exp, rel: good ? 0 : null, ok: good };
        if (!good) ok = false;
        continue;
      }
      const got = (raw === null || raw === undefined) ? null : Number(raw) / scale;
      const rel = (got === null || !Number.isFinite(got)) ? Infinity : relErr(got, exp);
      const good = rel <= TOL;
      rec.cmp[k] = { got, exp, rel: Number.isFinite(rel) ? rel : null, ok: good };
      if (!good) ok = false;
      rec.worst_rel = Math.max(rec.worst_rel, rel);
    }
    if (!Number.isFinite(rec.worst_rel)) rec.worst_rel = null;
    rec.pass = ok;
  } catch (e) {
    rec.error = String(e && e.message || e);
    rec.pass = false;
  }
  cases.push(rec);
}
await browser.close();
const total = cases.length;
const passed = cases.filter(c => c.pass).length;
const failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({ tool: 'dent_strain', file: 'dent_strain.html', reference: 'independent Python implementation of ASME B31.8-2022 Nonmandatory Appendix R dent strain equations (bench-src/ref/gen_dent_strain.py)', reference_citations: ['ASME B31.8-2022 Nonmandatory Appendix R'], tolerance: 'relative 2e-3 per quantity; verdict string equal', total, passed, failed, page_errors, cases }, { build: BUILD, reference_provenance: 'recomputed', provenance_note: 'generated by bench-src/ref/gen_dent_strain.py, independent of the tool code' }), null, 1));
console.log(`dent_strain: ${passed}/${total} passed`);
for (const c of cases.filter(c => !c.pass)) {
  const bad = Object.entries(c.cmp).filter(([, v]) => !v.ok).map(([k]) => k);
  console.log(`FAIL ${c.id}: ${bad.join(', ') || '-'}${c.error ? ' error=' + c.error : ''}`);
}
process.exitCode = 0;
