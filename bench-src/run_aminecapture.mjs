import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference values generated by bench-src/ref/gen_aminecapture.py, an independent Python re-implementation of the documented screening correlations (capture spec-02/03a/03b-04, ccus-spec-partial A1). Plus plant-data validation: specific reboiler duty vs published pilot/commercial data (Esbjerg, TCM 2018 MEA, Niederaussem CESAR1, Kaiserslautern, CEMCAP cement, Petra Nova) within +-10 %.' };
const P = benchPaths({ name: 'aminecapture', page: 'aminecapture.html', ref: 'aminecapture_ref.json' });
const TOL = 1e-9;
const ZERO_ABS = 1e-12;
const KEYS = ['q_reb', 'e_aux', 'steam', 'Q_cool', 'capex', 'cost_captured', 'cost_avoided', 'avoided_fraction', 'absorber_trains', 'absorber_D'];
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForTimeout(800);
const BUILD = await readPageManifestRevision(p);
const cases = [];
for (const cc of REF) {
  let got = {}, err = null;
  try {
    await p.evaluate(inputs => { const a = window.__aminecapture; Object.assign(a.state, inputs, { level: 'full', ownOps: true }); a.ui.sync(); a.ui.run(); }, cc.inputs);
    await p.waitForTimeout(120);
    got = await p.evaluate(keys => { const o = Diagram.record.build().outputs || {}; const n = v => (v && typeof v === 'object' && 'value' in v) ? v.value : v;
      const r = {}; for (const k of keys) r[k] = n(o[k]); return r; }, KEYS);
  } catch (e) { err = String(e && e.message || e); }
  const cmp = {};
  let worst_rel = 0, pass = !err;
  for (const k of KEYS) {
    const exp = cc.ref ? cc.ref[k] : undefined;
    if (exp === undefined || exp === null) continue;
    const g = got[k];
    let rel, ok;
    if (typeof g !== 'number' || !Number.isFinite(g)) { rel = Infinity; ok = false; }
    else if (k === 'absorber_trains') { rel = g === exp ? 0 : Math.abs(g - exp) / Math.max(Math.abs(exp), 1); ok = g === exp; }
    else if (k === 'absorber_D' && exp === 0) { rel = Math.abs(g); ok = Math.abs(g) <= ZERO_ABS; }
    else { rel = Math.abs(g - exp) / Math.max(Math.abs(exp), 1e-300); ok = rel <= (cc.tol ?? TOL); }
    cmp[k] = { got: g ?? null, exp, rel: Number.isFinite(rel) ? rel : null, ok };
    if (!Number.isFinite(rel) || rel > worst_rel) worst_rel = Number.isFinite(rel) ? rel : Infinity;
    if (!ok) pass = false;
  }
  const rec = { id: cc.id, kind: cc.kind || 'formula', note: cc.note, inputs: cc.inputs, cmp, worst_rel: Number.isFinite(worst_rel) ? worst_rel : null, pass };
  if (cc.kind === 'plant') Object.assign(rec, { tol: cc.tol, source: cc.source, q_range: cc.q_range, other: cc.other });
  if (err) rec.error = err;
  cases.push(rec);
}
await browser.close();
const total = cases.length; const passed = cases.filter(c => c.pass).length; const failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'aminecapture', file: 'aminecapture.html',
  reference: 'Independent re-implementation of documented correlations via bench-src/ref/gen_aminecapture.py',
  reference_citations: [
    'IEAGHG 2019-09 (2019) Further assessment of emerging CO2 capture technologies for the power sector',
    'NETL (2019) Cost and Performance Baseline for Fossil Energy Plants Vol.1 Rev4',
    'Moser P. et al. (2020) Int. J. Greenh. Gas Control (CESAR1)',
    'Rochelle G.T. et al. (2011) Chem. Eng. J. 171:725 (PZ)',
    'Abu-Zahra M.R.M. et al. (2007) Int. J. Greenh. Gas Control 1:37',
    'Knudsen J.N. et al. (2009) Energy Procedia 1:783 (Esbjerg CASTOR pilot, MEA)',
    'Faramarzi L., Gjernes E. et al. (2018-2019) TCM Mongstad MEA campaigns',
    'Moser P. et al. (2021) Int. J. Greenh. Gas Control 109 (Niederaussem CESAR1)',
    'Mangalapally H.P., Hasse H. (2010/2011) Kaiserslautern pilot plant, MEA',
    'CEMCAP project (2018) post-combustion MEA capture for cement',
    'CSLF/US DOE (2016-2020) Petra Nova W.A. Parish, KS-1'
  ],
  tolerance: 'formula cases: relative 1e-9 on record outputs (full precision), absorber_trains exact; plant cases (kind plant): relative 0.10 on q_reb vs published data',
  plant_validation: { total: cases.filter(c => c.kind === 'plant').length, passed: cases.filter(c => c.kind === 'plant' && c.pass).length, tol: 0.10 },
  total, passed, failed, page_errors, cases
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`aminecapture: ${passed}/${total} passed`);
for (const c of cases.filter(c => !c.pass)) { const bad = Object.entries(c.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} exp=${v.exp} rel=${v.rel}`).join('; '); console.log(`FAIL ${c.id}: ${c.error ? c.error + ' ' : ''}${bad}`); }
if (page_errors.length) console.log(`page errors: ${page_errors.length}`);
process.exitCode = 0;
