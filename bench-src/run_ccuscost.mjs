import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import { readPageManifestRevision, stampProvenance } from './provenance.mjs';
import { benchPaths } from './benchpaths.mjs';
const PROVENANCE = { reference_provenance: 'recomputed', provenance_note: 'Reference values generated by bench-src/ref/gen_ccuscost.py, an independent stdlib Python implementation of textbook project-finance definitions (CRF, point-flow NPV from construction start, bisection IRR, interpolated simple/discounted payback after COD, PV-cost over PV-tonnes LCOC) and bench-src/ref/gen_ccuscost_solve.py, an independent stdlib Python implementation of the simplified stage models, stage cost aggregation and IEAGHG/EU ETS/CRCF tonnes accounting.' };
const P = benchPaths({ name: 'ccuscost', page: 'ccuscost.html', ref: 'ccuscost_ref.json' });
const TOL = 1e-6;
const ABS_TOL = 1e-9;
const CASHFLOW_KEYS = ['npv', 'irr', 'payback', 'disc_payback', 'lcoc_stored', 'lcoc_avoided', 'lcoc_removed'];
const CRF_KEYS = ['crf'];
const SOLVE_KEYS = ['q_reb', 'w_comp', 'elec_MWh_y', 'gas_MWh_y', 't_stored', 't_ieaghg', 't_ets', 't_removed', 'metric_t', 'method', 'capture_eur_t', 'compression_eur_t', 'transport_eur_t', 'storage_eur_t', 'lcoc_simple', 'cost_per_t_avoided'];
const ABS_KEYS = new Set(['irr', 'payback', 'disc_payback']);
const REF = JSON.parse(fs.readFileSync(P.ref, 'utf8'));
const browser = await chromium.launch();
const p = await browser.newPage();
const page_errors = [];
p.on('pageerror', e => page_errors.push(String(e && e.message || e)));
await p.goto(P.pageUrl + '?lang=en');
await p.waitForFunction(() => !!(window.CCUS && window.CCUS.cost && window.CCUS.cost._internal), null, { timeout: 15000 }); await p.waitForTimeout(300);
const BUILD = await readPageManifestRevision(p);
const cases = [];
for (const cc of REF) {
  const keys = cc.kind === 'crf' ? CRF_KEYS : cc.kind === 'solve' ? SOLVE_KEYS : CASHFLOW_KEYS;
  let got = {}, err = null;
  try {
    got = await p.evaluate(({ kind, inputs, keys }) => {
      const I = window.CCUS.cost._internal;
      // crf inputs are expected as { r, n }
      let res;
      if (kind === 'solve') {
        // simplified in-hub stage models only: hide the stage modules during the call
        const C = window.CCUS, mods = ['capture', 'compress', 'pipe', 'ship', 'storage'], keep = {};
        for (const m of mods) { keep[m] = C[m]; C[m] = undefined; }
        let r;
        try { r = C.cost.solve(inputs); } finally { for (const m of mods) C[m] = keep[m]; }
        const st = s => { const b = r.breakdown.find(x => x.stage === s); return b ? b.total_eur_t : null; };
        res = !r.ok ? null : { q_reb: r.stages.capture.q_reb_GJ_t, w_comp: r.stages.compression ? r.stages.compression.w_el_kWh_t : 0,
          elec_MWh_y: r.energy.elec_MWh_y, gas_MWh_y: r.energy.gas_MWh_y, t_stored: r.t.stored, t_ieaghg: r.t.ieaghg,
          t_ets: r.t.ets, t_removed: r.t.removed_net, metric_t: r.t.metric, method: r.t.method,
          capture_eur_t: st('capture'), compression_eur_t: st('compression'), transport_eur_t: st('transport'),
          storage_eur_t: st('storage'), lcoc_simple: r.lcoc_simple, cost_per_t_avoided: r.cost_per_t_avoided };
      } else res = kind === 'crf' ? { crf: I.crf(inputs.r, inputs.n) } : I.cashflow(inputs);
      const out = {};
      for (const k of keys) out[k] = res == null || res[k] === undefined ? null : res[k];
      return out;
    }, { kind: cc.kind, inputs: cc.inputs, keys });
  } catch (e) { err = String(e && e.message || e); }
  const cmp = {};
  let worst_rel = 0, pass = !err;
  for (const k of keys) {
    const exp = cc.ref[k];
    const g = got && got[k] !== undefined ? got[k] : null;
    let rel, ok;
    if (exp === null || exp === undefined) {
      ok = g === null; rel = ok ? 0 : Infinity;
    } else if (typeof exp === 'string') {
      ok = g === exp; rel = ok ? 0 : Infinity;
    } else if (typeof g !== 'number' || !Number.isFinite(g)) {
      ok = false; rel = Infinity;
    } else {
      const abs = Math.abs(g - exp);
      rel = abs / Math.max(Math.abs(exp), 1e-300);
      ok = rel <= TOL || (ABS_KEYS.has(k) && abs <= ABS_TOL);
    }
    cmp[k] = { got: g, exp: exp === undefined ? null : exp, rel, ok };
    if (rel > worst_rel) worst_rel = rel;
    if (!ok) pass = false;
  }
  const rec = { id: cc.id, kind: cc.kind, note: cc.note, inputs: cc.inputs, cmp, worst_rel, pass };
  if (err) rec.error = err;
  cases.push(rec);
}
await browser.close();
const total = cases.length, passed = cases.filter(c => c.pass).length, failed = total - passed;
fs.writeFileSync(P.out, JSON.stringify(stampProvenance({
  tool: 'ccuscost',
  file: 'ccuscost.html',
  reference: 'Independent stdlib-Python references bench-src/ref/gen_ccuscost.py (economics) and bench-src/ref/gen_ccuscost_solve.py (solve level, simplified in-hub stage models)',
  reference_citations: ["IEAGHG (2013/TR4) Toward a common method of cost estimation for CO2 capture and storage at fossil fuel power plants", "Brealey, Myers, Allen, Principles of Corporate Finance (NPV, IRR, payback)", "Rubin et al. 2015 (IEAGHG cost of CO2 avoided)", "MRR (EU) 2018/2066 Art. 38(5), 49", "Reg. (EU) 2024/3012 (CRCF, BioCCS)"],
  tolerance: 'relative 1e-6 on numeric outputs (double precision, closed-form + bisection IRR); null must match null; method string exact',
  scope: 'Covers ccuscost economics and solve-level results using the simplified in-hub stage models (stage modules hidden). Not covered: external stage modules (amine capture, compressor, pipeline, ship, storage tools) when loaded, and correctness of cost-basis constants, which are only plausibility-checked against literature.',
  total, passed, failed, page_errors, cases
}, { build: BUILD, ...PROVENANCE }), null, 1));
console.log(`ccuscost: ${passed}/${total} passed`);
for (const c of cases.filter(c => !c.pass)) {
  const bad = Object.entries(c.cmp).filter(([, v]) => !v.ok).map(([k, v]) => `${k} got=${v.got} exp=${v.exp} rel=${v.rel}`).join('; ');
  console.log(`FAIL ${c.id}: ${c.error ? c.error + ' ' : ''}${bad}`);
}
if (page_errors.length) console.log(`page errors: ${page_errors.length}`);
process.exitCode = 0;
