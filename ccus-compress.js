/* chunk c02 (Claude, 2026-10-19): automatic staging, equal ratio incl. intercooler dp.
   Mechanical edit per the model's own note: core.polyStep(...) -> polyStep(...) (standalone, chunk c01). */
function planStages(core, pin, Tin, pout, Tic, m) {
  var N = m.N || 20, EPS = 1e-9;

  function dpOf(p) { return Math.max(0.015 * p, 1e4); }

  function solveRatio(n) {
    var r = Math.pow(pout / pin, 1 / n), k, i, p;
    for (k = 0; k < 3; k++) {
      p = pin;
      for (i = 0; i < n; i++) {
        p *= r;
        if (i < n - 1) p -= dpOf(p);
      }
      if (!(p > 0)) { r *= 1.1; continue; }
      r *= Math.pow(pout / p, 1 / n);
    }
    return r;
  }

  function build(n) {
    var r = solveRatio(n), stages = [], ok = true;
    var p1 = pin, T1 = Tin, i, p2, res, ri;
    for (i = 0; i < n; i++) {
      p2 = (i === n - 1) ? pout : p1 * r;
      ri = p2 / p1;
      if (!(p1 > 0) || !(ri > 0)) { ok = false; break; }
      res = polyStep(core, p1, T1, p2, m.etap, N);
      stages.push({
        pin: p1, Tin: T1, pout: p2, Tout: res.T,
        w: res.w, rhoOut: res.rho, r: ri
      });
      if (ri > m.rmax * (1 + EPS) || res.T > m.Tmax) ok = false;
      if (i < n - 1) {
        p1 = p2 - dpOf(p2);
        T1 = Tic;
      }
    }
    return { n: n, r: r, stages: stages, ok: ok };
  }

  var nmin = Math.max(1, Math.ceil(Math.log(pout / pin) / Math.log(m.rmax) - EPS));
  var n, plan;
  for (n = nmin; n <= m.nmax; n++) {
    plan = build(n);
    if (plan.ok) return { n: plan.n, r: plan.r, stages: plan.stages };
  }
  plan = build(m.nmax);
  return { n: plan.n, r: plan.r, stages: plan.stages, limited: true };
}
