function stageDuties(core, plan, mdot, Tic, m) {
  var T_REC = 403.15, MW_H2O = 18.015, MW_CO2 = 44.01;

  function wSat(p, T) {
    var y = yH2O(p, T);
    if (y >= 1) { y = 0.999999; }
    if (y < 0) { y = 0; }
    return y / (1 - y) * MW_H2O / MW_CO2;
  }

  var tot = { shaft: 0, el: 0, Qc: 0, Qrec: 0, water: 0 };
  var stages = (plan && plan.stages) || [];
  var wCarry = null;

  for (var i = 0; i < stages.length; i++) {
    var s = stages[i];

    var shaft = mdot * s.w / (1 - m.loss);
    var el = shaft / m.etaMotor;

    var hOut = core.props(s.pout, s.Tout).h;
    var hIc = core.props(s.pout, Tic).h;
    var Qc = mdot * (hOut - hIc);

    var Qrec = 0;
    if (s.Tout > T_REC) {
      var hRec = core.props(s.pout, T_REC).h;
      Qrec = 0.9 * mdot * Math.max(0, hOut - hRec);
    }

    var wIn = (i === 0 || wCarry === null) ? wSat(s.pin, s.Tin) : wCarry;
    var wOutSat = wSat(s.pout, Tic);
    var water = mdot * Math.max(0, wIn - wOutSat);
    var wOut = Math.min(wIn, wOutSat);
    wCarry = wOut;

    s.shaft = shaft;
    s.el = el;
    s.Qc = Qc;
    s.Qrec = Qrec;
    s.wIn = wIn;
    s.wOut = wOut;
    s.water = water;

    tot.shaft += shaft;
    tot.el += el;
    tot.Qc += Qc;
    tot.Qrec += Qrec;
    tot.water += water;
  }

  return tot;
}
