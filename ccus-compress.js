function psatW(T) {
  var t = T - 273.15;
  return 1e5 * 0.0061121 * Math.exp((18.678 - t / 234.5) * t / (257.14 + t));
}

function yH2O(p, T) {
  var t = T - 273.15;
  var pb = p / 1e5;
  var a = 0.0125 + 0.0003 * (35 - t);
  return Math.min(1, psatW(T) / p * Math.exp(a * (pb - 1)));
}

function polyStep(core, p1, T1, p2, eta, N) {
  var i, pn, hs, st, h, s, hin, sin, wIsen, r;
  function fin(x) { return typeof x === "number" && isFinite(x); }
  if (!fin(p1) || !fin(T1) || !fin(p2) || !fin(eta) || !fin(N)) {
    throw new Error("polyStep: non-finite input");
  }
  if (p2 <= p1) throw new Error("polyStep: p2 must be greater than p1");
  if (eta <= 0) throw new Error("polyStep: eta must be positive");
  N = Math.max(1, Math.round(N));
  st = core.props(p1, T1);
  h = st.h;
  s = st.s;
  if (!fin(h) || !fin(s)) throw new Error("polyStep: non-finite inlet state");
  hin = h;
  sin = s;
  for (i = 1; i <= N; i++) {
    pn = (i === N) ? p2 : p1 * Math.pow(p2 / p1, i / N);
    hs = core.ps(pn, s).h;
    if (!fin(hs)) throw new Error("polyStep: non-finite isentropic enthalpy at step " + i);
    h += (hs - h) / eta;
    st = core.ph(pn, h);
    s = st.s;
    if (!fin(h) || !fin(s) || !fin(st.T)) throw new Error("polyStep: non-finite state at step " + i);
  }
  wIsen = core.ps(p2, sin).h - hin;
  r = { T: st.T, h: h, s: s, rho: st.rho, hin: hin, w: h - hin, wIsen: wIsen };
  if (!fin(r.T) || !fin(r.rho) || !fin(r.w) || !fin(r.wIsen)) {
    throw new Error("polyStep: non-finite result");
  }
  return r;
}
