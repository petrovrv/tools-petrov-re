function costs(machine, P_comp_shaft, P_pump_shaft, dehyType, mdot, liqOn, e) {
  var items = [], warnings = [], capex = 0, om = 0;
  var tph = mdot * 3.6, tpy = tph * e.hours;

  function add(key, Cref, Sref, n, S, omFrac) {
    if (!(S > 0)) return;
    var ratio = S / Sref, c = Cref * Math.pow(ratio, n);
    if (ratio < 0.3 || ratio > 3) {
      warnings.push(key + ': size ' + S.toPrecision(3) + ' is ' + ratio.toFixed(2) + 'x reference ' + Sref + ' (valid 0.3-3x)');
    }
    items.push({key: key, capex: c});
    capex += c;
    om += omFrac * c;
  }

  var m = COST[machine];
  if (!m || m.om === undefined) throw new Error('Unknown compressor type: ' + machine);
  add(machine, m.c * m.S / 1000, m.S, m.n, P_comp_shaft, m.om);

  var p = COST.PUMP;
  add('PUMP', p.c * p.S / 1000, p.S, p.n, P_pump_shaft, 0.04);

  if (dehyType && dehyType !== 'NONE') {
    var d = COST[dehyType];
    if (!d || d.C === undefined) throw new Error('Unknown dehydration type: ' + dehyType);
    add(dehyType, d.C, d.S, d.n, tph, 0.04);
  }

  if (liqOn) {
    var l = COST.LIQ;
    add('LIQ', l.c * l.S, l.S, l.n, tpy, 0.04);
  }

  var r = e.rate, L = e.life, f = Math.pow(1 + r, L);
  var crf = r > 0 ? r * f / (f - 1) : 1 / L;
  var a = {
    capital: crf * capex,
    om: om,
    elec: (e.el || 0) * e.hours / 1e6 * e.elecPrice,
    heat: (e.heat || 0) * e.hours / 1e6 * (e.heatPrice || 0)
  };
  a.total = a.capital + a.om + a.elec + a.heat;

  return {items: items, capex: capex, crf: crf, annual: a,
    perTonne: tpy > 0 ? a.total / tpy : NaN, warnings: warnings};
}
