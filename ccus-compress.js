function solveCore(core, inp) {
  var warnings = [], m = inp.m || {}, mdot = inp.mdot;
  var ship = inp.dest === 'shipMP' || inp.dest === 'shipLP';
  var mode = inp.dest === 'shipMP' ? 'MP' : 'LP';
  var usePump = !ship && !!inp.pumpOn && inp.pout > inp.pSwitch;
  var pTarget = ship ? (mode === 'MP' ? 15e5 : 7e5) : (usePump ? inp.pSwitch : inp.pout);
  var plan, duties, pump = null, liq = null, dh, last, rho, water, wStage, i, pOut, Tout;

  function lastStage() {
    var s = plan.stages || [];
    return s.length ? s[s.length - 1] : { pin: inp.pin, Tin: inp.Tin, pout: inp.pin, Tout: inp.Tin, w: 0, wOut: 0 };
  }

  function runPlan(pt) {
    plan = planStages(core, inp.pin, inp.Tin, pt, inp.Tic, m);
    if (plan.limited) {
      warnings.push('Compressor plan limited (rmax/nmax/Tmax) when targeting ' + (pt / 1e5).toFixed(1) + ' bar');
    }
    duties = stageDuties(core, plan, mdot, inp.Tic, m);
  }

  runPlan(pTarget);

  if (usePump) {
    rho = core.props(inp.pSwitch, inp.Tpump).rho;
    if (rho < 600) {
      warnings.push('CO2 density at pump inlet ' + rho.toFixed(0) + ' kg/m3 < 600; pump disabled, compressing to outlet pressure');
      usePump = false;
      runPlan(inp.pout);
    } else {
      last = lastStage();
      pump = densePump(core, inp.pSwitch, inp.Tpump, inp.pout, mdot, inp.etaPump, inp.etaPumpMotor);
      duties.Qc += Math.max(0, mdot * (core.props(inp.pSwitch, inp.Tic).h - core.props(inp.pSwitch, inp.Tpump).h));
    }
  }

  if (ship) {
    liq = liquefy(core, pTarget, inp.Tic, mdot, mode, { Tcw: inp.Tcw });
  }

  wStage = null;
  for (i = 0; i < (plan.stages || []).length; i++) {
    if (plan.stages[i].pout >= 30e5) { wStage = plan.stages[i]; break; }
  }
  if (!wStage) wStage = lastStage();
  water = mdot * (wStage.wOut || 0);
  dh = dehydration(String(inp.dehy || 'none').toLowerCase(), mdot, water);

  last = lastStage();
  if (pump) { pOut = inp.pout; Tout = pump.Tout; }
  else if (liq) { pOut = liq.pLiq; Tout = liq.Tliq; }
  else { pOut = last.pout; Tout = inp.Tic; }

  return {
    plan: plan, duties: duties, pump: pump, liq: liq, dh: dh,
    pOut: pOut, Tout: Tout,
    elTotal: (duties.el || 0) + (pump ? pump.el : 0) + (liq ? liq.el : 0) + (dh && dh.el ? dh.el : 0),
    shaftComp: duties.shaft || 0,
    shaftPump: pump ? pump.shaft : 0,
    warnings: warnings
  };
}
