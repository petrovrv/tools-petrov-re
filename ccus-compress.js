function densePump(core, p1, T1, p2, mdot, eta, etaMotor) {
  var r = polyStep(core, p1, T1, p2, eta, 20);
  var shaft = mdot * r.w;
  return { Tout: r.T, w: r.w, shaft: shaft, el: shaft / etaMotor };
}

function dehydration(type, mdot, waterIn) {
  var kWhPerT = 3.6e6 / 1000;
  var heatPerKg, elPerKg;
  if (type === 'teg') { heatPerKg = 12e6; elPerKg = 0.3 * kWhPerT; }
  else if (type === 'molsieve') { heatPerKg = 8e6; elPerKg = 0.75 * kWhPerT; }
  else if (type === 'none') { return { heat: 0, el: 0 }; }
  else { throw new Error('dehydration: unknown type ' + type); }
  return { heat: heatPerKg * waterIn, el: elPerKg * mdot };
}

function liquefy(core, pIn, TIn, mdot, mode, m) {
  var pLiq;
  if (mode === 'LP') { pLiq = 7e5; }
  else if (mode === 'MP') { pLiq = 15e5; }
  else { throw new Error('liquefy: unknown mode ' + mode); }
  var Tsat = core.satP(pLiq).T;
  var Tliq = Tsat - 2;
  var hIn = core.props(pLiq, TIn).h;
  var hLiq = core.props(pLiq, Tliq).h;
  var Q = mdot * (hIn - hLiq);
  var Tevap = Tsat - 5;
  var Tcond = m.Tcw + 10;
  if (Tcond <= Tevap) { throw new Error('liquefy: Tcond must exceed Tevap'); }
  var COP = 0.55 * Tevap / (Tcond - Tevap);
  return { Q: Q, COP: COP, el: Q / COP * 1.05, Tliq: Tliq, pLiq: pLiq };
}
