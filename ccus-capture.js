function num(v, d) {
  var n = (typeof v === 'string' && v !== '') ? parseFloat(v) : v;
  return (typeof n === 'number' && isFinite(n)) ? n : d;
}
function clamp(v, a, b) {
  return v < a ? a : (v > b ? b : v);
}
function merge(a, b) {
  var o = {}, k;
  for (k in a) { if (Object.prototype.hasOwnProperty.call(a, k)) { o[k] = a[k]; } }
  if (b) {
    for (k in b) {
      if (Object.prototype.hasOwnProperty.call(b, k) && b[k] !== undefined) { o[k] = b[k]; }
    }
  }
  return o;
}
function ceil(v) {
  return Math.ceil(v - 1e-9);
}
