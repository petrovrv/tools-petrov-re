/* ---- cC: sizing, costs, capture-rate curve (Claude) ---- */
function sizing(x, en) {
  if (en.hp) return { hp: true };
  var Vact = en.nFlue * 1000 * 8.314 * 313.15 / 101325;
  var A = Vact / K.uGas;
  var Dreq = Math.sqrt(4 * A / Math.PI);
  var nTrains = Math.max(1, ceil(Math.pow(Dreq / K.Dmax, 2)));
  var Dabs = Math.sqrt(4 * A / nTrains / Math.PI);
  var Dstr = K.strFrac * Dabs;
  return {
    Vact: Vact, A: A, Dreq: Dreq, nTrains: nTrains,
    Dabs: Dabs, Dstr: Dstr, hPack: K.hPack, packVol: A * K.hPack
  };
}

function crf(i, n) {
  if (typeof CCUS !== 'undefined' && CCUS && CCUS.core && CCUS.core.econ &&
      typeof CCUS.core.econ.crf === 'function') {
    return CCUS.core.econ.crf(i, n);
  }
  i = num(i); n = num(n);
  if (n <= 0) return 0;
  if (i === 0) return 1 / n;
  var p = Math.pow(1 + i, n);
  return i * p / (p - 1);
}

function costs(x, en) {
  var h = x.hours * 3600;
  var tpa = en.mdot * h / 1000;
  var capex, items = {}, k;
  if (en.hp) {
    capex = K.hpCapexPerTpa * tpa * x.capexFactor;
    items = { dehydration: capex };
  } else {
    var S = en.mdot / K.mdotRef;
    var F = (en.mdot / x.y) / (K.mdotRef / K.yRef);
    capex = K.capexRef * x.capexFactor *
      (K.flueShare * Math.pow(F, K.expo) + (1 - K.flueShare) * Math.pow(S, K.expo));
    for (k in K.split) {
      if (K.split.hasOwnProperty(k)) items[k] = capex * K.split[k];
    }
  }
  var f = crf(x.rate, x.life);
  var capital = capex * f;
  var fixedOM = capex * K.fixedOM + (en.hp ? 0.25 : 1) * K.labour;
  var src = x.heatSource || x.heat, heat = 0;
  if (src === 'steam') {
    heat = en.Qext * h / 1e9 * x.steamPrice;
  } else if (src === 'extraction') {
    heat = en.PelLost * h / 3.6e9 * x.elecPrice;
  } else if (src === 'gasBoiler') {
    heat = en.fuel * h / 3.6e9 * x.gasPrice + en.co2Fuel * h / 1000 * x.co2Price;
  } else if (src === 'eBoiler' || src === 'heatPump') {
    heat = en.PelHeat * h / 3.6e9 * x.elecPrice;
  }
  heat = num(heat, 0);
  var elec = en.Paux * h / 3.6e9 * x.elecPrice;
  var sv = SOLVENTS[x.solvent];
  var solvent = (en.hp || !sv) ? 0 : sv.makeup * sv.price * tpa;
  var cooling = en.Qcool * h / 1e9 * x.cwPrice;
  var total = capital + fixedOM + heat + elec + solvent + cooling;
  var annual = {
    capital: capital, fixedOM: fixedOM, heat: heat, elec: elec,
    solvent: solvent, cooling: cooling, total: total
  };
  var perTonne = {};
  for (k in annual) {
    if (annual.hasOwnProperty(k)) perTonne[k] = tpa > 0 ? annual[k] / tpa : null;
  }
  var avoidedT = en.netAvoided * h / 1000;
  var perAvoided = avoidedT > 0 ? total / avoidedT : null;
  return {
    capex: capex, items: items, tpa: tpa, annual: annual,
    perTonne: perTonne, perAvoided: perAvoided, crf: f
  };
}

function curve(x, solveFn) {
  var etas = [], seen = {}, i, e, key, out = [], r;
  for (i = 0; i <= 12; i++) etas.push(Math.round((0.50 + 0.04 * i) * 100) / 100);
  etas.push(0.90, 0.95);
  etas.sort(function (a, b) { return a - b; });
  for (i = 0; i < etas.length; i++) {
    e = etas[i];
    key = e.toFixed(2);
    if (seen[key]) continue;
    seen[key] = true;
    r = solveFn(merge(x, { eta: e }));
    if (r && r.ok) {
      out.push({
        eta: e,
        qGJ: r.qGJ,
        perTonne: r.perTonne ? r.perTonne.total : null,
        perAvoided: r.perAvoided
      });
    }
  }
  return out;
}
