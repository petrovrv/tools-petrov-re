/* ---- cB: energy balance (Claude); glue fix: GJ/t -> J/kg is 1e6 (not 1e9) ---- */
function energy(x) {
  function nz(v, d) { return (v === null || v === undefined || v === '' || isNaN(+v)) ? d : +v; }
  var w = [];
  var sid = x.solvent, s = SOLVENTS[sid];
  if (!s) { w.push('Unknown solvent: ' + sid); sid = 'MEA'; s = SOLVENTS.MEA; }
  var mdotSrc = Math.max(0, nz(x.mdotSrc, 0));
  var y = clamp(nz(x.y, 0.12), 1e-6, 1);
  var eta = clamp(nz(x.eta, 0.9), 0, 1);
  var whFrac = clamp(nz(x.whFrac, 0), 0, 1);
  var gridEF = Math.max(0, nz(x.gridEF, 0));
  var fanDp = nz(x.fanDp, K.fanDp);
  var a = nz(x.alphaLean, s.alphaOpt);
  var pStr = nz(x.pStr, s.pStr);
  var mdot = mdotSrc * eta, hp = y >= K.hpThreshold, ypct = 100 * y;
  var q, fEta = 1, fLL = 1, fP = 1, Pfan = 0, circ = 0;
  var nFlue = mdotSrc / K.M / y, Vflue = nFlue * K.Vn;
  var aux = { fan: 0, pumps: 0, cw: 0, other: 0, dehy: 0 };
  if (hp) {
    q = K.hpQreb;
    aux.dehy = K.hpAux;
  } else {
    var aO = s.alphaOpt;
    fEta = 1 + 1.5 * Math.max(0, eta - 0.90);
    fLL = 1 + 0.10 * Math.max(0, (aO - a) / 0.05) + 0.05 * Math.max(0, (a - aO) / 0.05);
    var isPZ = /pz/i.test(String(sid)) || s.type === 'PZ';
    fP = isPZ ? 1 - 0.02 * (pStr / 1e5 - 6) : 1 - 0.04 * (pStr / 1e5 - 1.9);
    // refit 2026-10-19.2 to pilot data: Esbjerg 12% 3.6-3.7, TCM 4% 3.6-3.8, CEMCAP ~3.5 (Claude)
    q = (3.45 + 1.2 / ypct) * fEta * s.fs * fLL * fP;
    if (Math.abs(a - aO) > 0.10) w.push('Lean loading far from optimum (' + a.toFixed(3) + ' vs ' + aO + ')');
    if (pStr < s.pMin || pStr > s.pMax) w.push('Stripper pressure outside solvent range [' + s.pMin / 1e5 + '-' + s.pMax / 1e5 + ' bar]');
    if (eta > 0.98) w.push('Capture fraction >98%: model extrapolated');
    if (eta < 0.5) w.push('Capture fraction <50%: atypical design');
    if (ypct < 3) w.push('CO2 content <3 mol%: model extrapolated');
    if (ypct > 30) w.push('CO2 content >30 mol%: amine correlation extrapolated');
    Pfan = Vflue * fanDp / K.etaFan;
    aux.fan = mdot > 0 ? Pfan / mdot / 3600 : 0;
    aux.pumps = K.ePumps;
    aux.cw = K.eCwPerGJ * q;
    aux.other = K.eOther;
    var swing = s.alphaRich - a;
    if (swing < 0.1) w.push('Loading swing <0.1 mol/mol: high circulation');
    circ = swing > 0 ? 1000 / (44 * s.C * swing) * mdot / 1000 : Infinity;
  }
  var auxKWh = aux.fan + aux.pumps + aux.cw + aux.other + aux.dehy;
  var eAux = auxKWh * 3600;
  var Paux = auxKWh * mdot * 3600;
  var Qreb = q * 1e6 * mdot;
  var Qcool = hp ? 0.1 * q * 1e6 * mdot : (K.cwFactor * q + K.cwAdd) * 1e6 * mdot;
  var Qext = Qreb * (1 - whFrac);
  var steam = Qext / K.rfg;
  var PelHeat = 0, PelLost = 0, fuel = 0, co2Fuel = 0;
  switch (x.heat) {
    case 'steam': break;
    case 'extraction': PelLost = Qext / 1e9 * HEAT.extraction.kWhePerGJ * 3.6e6; break;
    case 'gasBoiler': fuel = Qext / HEAT.gasBoiler.eta; co2Fuel = fuel * HEAT.gasBoiler.ef / 3.6e6; break;
    case 'eBoiler': PelHeat = Qext / HEAT.eBoiler.eta; break;
    case 'heatPump': PelHeat = Qext / HEAT.heatPump.cop; break;
    default: w.push('Unknown heat source: ' + x.heat);
  }
  var co2Ind = co2Fuel + (Paux + PelHeat + PelLost) * gridEF / 3.6e6;
  var netAvoided = mdot - co2Ind;
  var avoidedFrac = mdotSrc > 0 ? netAvoided / mdotSrc : 0;
  if (netAvoided < 0) w.push('Indirect emissions exceed captured CO2');
  return {
    hp: hp, mdot: mdot, q: q * 1e6, qGJ: q, fEta: fEta, fLL: fLL, fP: fP,
    alphaLean: a, pStr: pStr, Vflue: Vflue, nFlue: nFlue, Pfan: Pfan,
    aux: aux, auxKWh: auxKWh, eAux: eAux, Paux: Paux, circ: circ,
    Qreb: Qreb, Qcool: Qcool, steam: steam, Qext: Qext,
    PelHeat: PelHeat, PelLost: PelLost, fuel: fuel, co2Fuel: co2Fuel,
    co2Ind: co2Ind, netAvoided: netAvoided, avoidedFrac: avoidedFrac, warnings: w
  };
}
