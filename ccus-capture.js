function _bad(v) { return typeof v !== 'number' || !isFinite(v); }
function _fail(msg) { return { ok: false, error: msg, warnings: [] }; }

function solve(inp) {
  var x = merge(DEFAULTS, inp || {});
  if (_bad(x.mdotSrc) || x.mdotSrc <= 0) return _fail('mdotSrc must be > 0');
  if (_bad(x.y) || x.y <= 0 || x.y > 1) return _fail('y must be in (0,1]');
  if (_bad(x.eta) || x.eta <= 0 || x.eta > 1) return _fail('eta must be in (0,1]');
  if (!SOLVENTS[x.solvent]) return _fail('Unknown solvent: ' + x.solvent);
  if (!HEAT[x.heat]) return _fail('Unknown heat source: ' + x.heat);
  if (_bad(x.hours) || x.hours < 1 || x.hours > 8784) return _fail('hours must be in 1..8784');
  if (_bad(x.life) || x.life <= 0) return _fail('life must be > 0');

  var en, sz, c;
  try {
    en = energy(x);
    sz = sizing(x, en);
    c = costs(x, en);
  } catch (e) {
    return _fail(String((e && e.message) || e));
  }

  var warnings = (en.warnings || []).slice();
  var pt = c.perTonne;
  var breakdown = [
    { key: 'q_reb', label: 'Reboiler duty', value: en.qGJ, unit: 'GJ/t' },
    { key: 'e_fan', label: 'Flue gas fan', value: en.aux.fan, unit: 'kWh/t' },
    { key: 'e_pumps', label: 'Solvent pumps', value: en.aux.pumps, unit: 'kWh/t' },
    { key: 'e_cw', label: 'Cooling water', value: en.aux.cw, unit: 'kWh/t' },
    { key: 'e_other', label: 'Other auxiliaries', value: en.aux.other, unit: 'kWh/t' },
    { key: 'e_dehy', label: 'Dehydration', value: en.aux.dehy, unit: 'kWh/t' },
    { key: 'c_capital', label: 'Capital charge', value: pt.capital, unit: 'EUR/t' },
    { key: 'c_om', label: 'Fixed O&M', value: pt.fixedOM, unit: 'EUR/t' },
    { key: 'c_heat', label: 'Heat', value: pt.heat, unit: 'EUR/t' },
    { key: 'c_elec', label: 'Electricity', value: pt.elec, unit: 'EUR/t' },
    { key: 'c_solvent', label: 'Solvent make-up', value: pt.solvent, unit: 'EUR/t' },
    { key: 'c_cool', label: 'Cooling', value: pt.cooling, unit: 'EUR/t' }
  ];

  return {
    ok: true,
    warnings: warnings,
    inputs: x,
    hp: en.hp,
    mdot: en.mdot,
    tpa: c.tpa,
    qGJ: en.qGJ,
    E: en.q,
    Qreb: en.Qreb,
    steam: en.steam,
    steamPerT: en.steam / en.mdot,
    Paux: en.Paux,
    eAux: en.eAux,
    auxKWh: en.auxKWh,
    Qcool: en.Qcool,
    circ: en.circ,
    circPerT: en.circ / en.mdot * 1000, // m3/t
    Vflue: en.Vflue,
    co2Ind: en.co2Ind,
    netAvoided: en.netAvoided,
    avoidedFrac: en.avoidedFrac,
    factors: { fEta: en.fEta, fLL: en.fLL, fP: en.fP },
    sizing: sz,
    capex: c.capex,
    items: c.items,
    annual: c.annual,
    perTonne: c.perTonne,
    perAvoided: c.perAvoided,
    curve: x.withCurve ? curve(merge(x, { withCurve: false }), solve) : [],
    energy: en,
    breakdown: breakdown,
    handoff: {
      mdot: en.mdot, E: en.q, Q: en.Paux,
      sets: { capture: [{ mdot: en.mdot }, { E: en.q }, { Q: en.Paux }, { x: x.y }] }
    }
  };
}

